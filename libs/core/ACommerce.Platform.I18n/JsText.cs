using System.Globalization;
using System.Text;

namespace ACommerce.Platform.I18n;

/// <summary>
/// <para><b>طَبَقَةُ الهُروب إلى JS</b> — المَنفَذُ الثالِث بَعدَ
/// <c>this[key]</c> (خاصِّيَّة) و<c>Markup(key)</c> (عُقدَةُ نَصّ).
/// وسِياقُه ثالِثٌ لا مُشتَقّ: قيمَةٌ تُكتَب داخِلَ <b>حَرفِيَّةِ سِلسِلَة
/// JavaScript</b> داخِلَ عُنصُر <c>&lt;script&gt;</c> مَبثوثٍ في
/// المُستَند.</para>
///
/// <para><b>ولِماذا لا يَكفي أَيٌّ مِن المَنفَذَين القائِمَين</b>: مُرَمِّزُ
/// HTML يَهرُب <c>&lt; &gt; &amp; " '</c> إلى مَراجِعَ رَقَمِيَّة —
/// وهي <b>لا تُفَكّ</b> داخِلَ <c>&lt;script&gt;</c>، فَمُحَلِّلُ HTML
/// يَقرَأُ مُحتَواه نَصّاً خاماً (raw text). فَتَرميزُ HTML هُنا يَكسِر
/// النَصّ المَعروض بَدَل أَن يَحرُسَه. والكِتابَةُ الخام تَحرُس
/// البايتات وتَفتَح الهُروب مِن الحَرفِيَّة. فَالصَحيحُ ثالِثٌ:
/// <b>هُروبُ JavaScript</b>.</para>
///
/// <para><b>وثَلاثَةُ أَبوابٍ يَجِب أَن تُغلَق مَعاً</b>، وإغلاقُ
/// اثنَينِ مِنها هُروبٌ نِصفيّ لا يُقبَل:</para>
/// <list type="number">
///   <item><b>الخُروجُ مِن الحَرفِيَّة</b> — <c>'</c>، <c>"</c>،
///   <c>`</c>، <c>\</c>، و<c>$</c> (فَـ<c>${…}</c> يُنَفِّذ داخِلَ
///   حَرفِيَّةِ قالِب).</item>
///   <item><b>كَسرُ الجُملَة بِسَطرٍ جَديد</b> — <c>\n</c>، <c>\r</c>،
///   و<b>فاصِلا السَطر في JS وَحدَه</b> (‏U+2028 وU+2029): مَحرَفانِ
///   لا يَراهُما HTML سَطراً ويَراهُما مُحَلِّلُ JavaScript كَذلك،
///   فَيَكسِرانِ الجُملَةَ بِلا أَثَرٍ مَرئيّ.</item>
///   <item><b>الخُروجُ مِن العُنصُر نَفسِه</b> — <c>&lt;/script</c> و
///   <c>&lt;!--</c>: مُحَلِّلُ HTML يُنهي <c>&lt;script&gt;</c> عِندَ
///   أَوَّلِ <c>&lt;/script</c> <b>ولَو كانَ داخِلَ حَرفِيَّةِ JS</b>.
///   فَهُروبُ <c>&lt;</c> إلى <c>\u003C</c> يُغلِقُ البابَين مَعاً
///   بِفِعلٍ واحِد.</item>
/// </list>
///
/// <para><b>والبُرهانُ البايتيّ يَبقى قائِماً لِأَنّ الهُروبَ لا يَعمَل</b>:
/// كُلُّ قيمَةٍ في المَعجَم عَرَبِيَّةٌ خالِصَة، فَـ<see cref="Escape"/>
/// تُعيدُها <b>حَرفاً بِحَرف</b> — والسِلسِلَةُ المُصَيَّرَة هي عَينُ
/// الحَرفِيَّةِ الَّتي حَلَّت مَحَلَّها. وهذا ما يَحرُسُه
/// <c>value_unsafe_js</c> عِندَ البَوّابَة: قيمَةٌ تَحتاجُ هُروباً
/// تُغَيِّرُ بايتات الصَفحَة، فَتُرَدُّ قَبلَ أَن تُشحَن — لا بَعدَ أَن
/// تُقاس.</para>
/// </summary>
public static class JsText
{
    /// <summary>القيمَةُ صالِحَةً لِلكِتابَةِ داخِلَ حَرفِيَّةِ سِلسِلَةِ
    /// JavaScript (‏<c>'…'</c> أَو <c>"…"</c> أَو <c>`…`</c>) في عُنصُر
    /// <c>&lt;script&gt;</c>.</summary>
    public static string Escape(string value)
    {
        if (string.IsNullOrEmpty(value)) return value;

        StringBuilder? sb = null;
        for (var i = 0; i < value.Length; i++)
        {
            var replacement = Replacement(value[i]);
            if (replacement is null)
            {
                sb?.Append(value[i]);
                continue;
            }

            sb ??= new StringBuilder(value.Length + 16).Append(value, 0, i);
            sb.Append(replacement);
        }

        return sb?.ToString() ?? value;
    }

    /// <summary>هَل تُكتَبُ القيمَةُ خاماً بِلا تَبديلِ بايتٍ واحِد؟
    /// شَرطُ البُرهان البايتيّ، ومِعيارُ <c>value_unsafe_js</c>.</summary>
    public static bool IsVerbatim(string value)
        => string.Equals(Escape(value), value, StringComparison.Ordinal);

    /// <summary>المَحارِفُ الَّتي لا تُكتَبُ خاماً، ولِكُلٍّ بابُه في
    /// تَوثيق الصَنف. <c>null</c> = يُكتَبُ كَما هو.</summary>
    private static string? Replacement(char c) => c switch
    {
        // ── ١. الخُروجُ مِن الحَرفِيَّة ────────────────────────────────
        '\\' => "\\\\",
        '\'' => "\\'",
        '"' => "\\\"",
        '`' => "\\`",
        '$' => "\\$",

        // ── ٢. كَسرُ الجُملَة ──────────────────────────────────────────
        '\n' => "\\n",
        '\r' => "\\r",
        '\u2028' => "\\u2028",
        '\u2029' => "\\u2029",

        // ── ٣. الخُروجُ مِن العُنصُر: `</script` و`<!--` ──────────────
        //    و`>` و`&` مَعَه لِلتَناظُر مَعَ `value_unsafe_markup`،
        //    فَلا يَبقى مَحرَفٌ بِنيَويٌّ واحِدٌ يُكتَبُ خاماً.
        '<' => "\\u003C",
        '>' => "\\u003E",
        '&' => "\\u0026",

        // ── وما تَبَقّى مِن مَحارِف التَحَكُّم ──────────────────────────
        _ => c < 0x20 || (c >= 0x7F && c <= 0x9F)
            ? "\\u" + ((int)c).ToString("X4", CultureInfo.InvariantCulture)
            : null,
    };
}
