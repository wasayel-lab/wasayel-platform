namespace ACommerce.Kit.Theme;

/// <summary>
/// <para><b>حُزمَة جاهِزَة</b> — هُوِيَّة بَصَرِيَّة كامِلَة في مِلَفّ
/// واحِد: رُموز <b>ومُتَغايِرات</b> مَعاً. لَيسَت «لَوحَة أَلوان»: لَون
/// الواحَة عَلى شَكل اللَيل هُوِيَّة ثالِثَة لَم يُنَسِّقها أَحَد، وهي
/// بِالضَبط ما تَمنَعُه وَحدَةُ المِلَفّ.</para>
/// </summary>
/// <param name="Slug">مُعَرِّفُها — وهو أَيضاً سلاج وَثيقَة الثيم الَّتي
/// تُكتَب عِندَ التَطبيق، فَالمُستَأجِر يُعرَف مِنها أَيّ حُزمَة
/// يَحمِل.</param>
/// <param name="Label">تَسمِيَتُها المَعروضَة.</param>
/// <param name="Json">‏<b>نَصُّها كَما كُتِبَ</b> — وهو ما يُنسَخ حَرفاً
/// إلى وَثيقَة المُستَأجِر.</param>
/// <param name="Definition">الكائِن المُفَكَّك — لِلمُعايَنَة في سَطح
/// الإدارَة (مُرَبَّعات الأَلوان) بِلا إعادَة قِراءَة النَّصّ في كُلّ
/// تَصيير.</param>
public sealed record ThemePreset(
    string Slug, ThemeLabel Label, string Json, ThemeDefinition Definition);

/// <summary>
/// <para><b>كاتالوج الحُزَم الجاهِزَة</b> — ثَلاث اليَوم، مَضمونَة
/// مَوارِدَ ومُصادَقَة عِندَ أَوَّل مَسّ (وهو الإقلاع، لِأَنّ تَسجيل
/// الخِدمات يَمَسُّه صَراحَةً).</para>
///
/// <para><b>ولِماذا كاتالوج مُغلَق لا «مُجَلَّد يُقرَأ»</b>: زِرّ
/// «تَطبيق» في سَطح الإدارَة يُرسِل <b>اسم حُزمَة</b> لا نَصّ تَعريف —
/// فَما يَصِل قاعِدَة البَيانات مَكتوب في هذا المُستودَع، ولا يَملِك
/// أَحَد أَن يَحقِن ثيماً بِصِياغَة طَلَب. المُصادِق ما زالَ يَعمَل
/// خَلفَه (الاقتِراح والاعتِماد كِلاهُما يُصادِق)، لكِنّ الإغلاق هُنا
/// يَجعَل السالِبَ مُستَحيلاً بِالبِناء لا مَردوداً بِالفَحص.</para>
///
/// <para><b>والتَطبيق نَسخ لا إحالَة</b> — القَرار مُعلَن ومَقصود:
/// وَثيقَة المُستَأجِر تَحمِل <b>بايتات الحُزمَة يَومَ طُبِّقَت</b>، لا
/// إشارَةً إلَيها. فَتَعديل مِلَفّ حُزمَة غَداً لا يُغَيِّر مَتجَراً
/// يَعمَل، ونَشرُ نُسخَة جَديدَة لا يُبَدِّل مَظهَر عَرضٍ قائِم. الإحالَة
/// كانَت سَتُوَصِّل التَحديثات — وهذه فَضيلَة في مَكتَبَة ورَذيلَة في
/// عَرض: ما يُرى في الشاشَة يَجِب أَن يَكون ما اعتُمِدَ، لا ما صارَ
/// إلَيه المِلَفّ بَعدَه.</para>
/// </summary>
public static class ThemePresetCatalog
{
    private static readonly Lazy<IReadOnlyList<ThemePreset>> LazyAll =
        new(ThemeDefinitionLoader.LoadEmbeddedPresets, isThreadSafe: true);

    /// <summary>الحُزَم بِتَرتيب السلاج — تَرتيب ثابِت بَين
    /// الإقلاعات.</summary>
    public static IReadOnlyList<ThemePreset> All => LazyAll.Value;

    public static ThemePreset? Find(string slug) =>
        All.FirstOrDefault(p => string.Equals(p.Slug, slug, StringComparison.Ordinal));

    public static bool Contains(string slug) => Find(slug) is not null;

    public static int Count => All.Count;

    /// <summary>مَسّ صَريح يُجبِر القِراءَة والمُصادَقَة الآن. يُنادى
    /// عِندَ تَسجيل الخِدمات، فَخَلَل حُزمَة يَظهَر عِندَ الإقلاع لا
    /// عِندَ أَوَّل نَقرَة.</summary>
    public static int Preload() => All.Count;
}
