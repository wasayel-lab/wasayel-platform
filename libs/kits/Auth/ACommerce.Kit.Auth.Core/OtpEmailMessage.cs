namespace ACommerce.Kit.Auth;

// ═══ نَصُّ رِسالَةِ رَمزِ الدُخول — مَوضِعٌ واحِدٌ لا نُسخَة ═══════════
//
// **لِماذا اُستُخرِج (‏2026-08-23) — قَبلَ أَن يَنسَخَه نَقلٌ ثانٍ**:
// قَناةُ بَريدٍ ثانِيَة (‏HTTPS بَدَلَ SMTP) تُرسِلُ **الرِسالَةَ نَفسَها**
// بِنَقلٍ آخَر. ونُسخَتانِ مِن نَصٍّ عَرَبيٍّ مُشَكَّلٍ لا تَبقَيانِ
// مُتَطابِقَتَين: تُصَحَّح إحداهُما فَتَنجَرِف الأُخرى صامِتَةً، ولا
// يَراها إلّا مَن يَقرَأ صُندوقَ بَريدِه بِالقَناةِ الأُخرى. والاستِخراجُ
// اليَومَ نَقلُ أَسطُر، وغَداً — بَعدَ النَسخ — مُقارَنَةُ تَشكيل.
//
// **وما لَم يُنقَل هُنا**: العُنوانُ يَبقى في القامُوسِ (`ar.json`) —
// فَمَصدَرُه واحِدٌ أَصلاً، والمَنقولُ هُنا **مِفتاحُه** لا نَصُّه، لِئَلّا
// يُنسَخَ المِفتاحُ حَرفِيّاً في قَناتَين.
//
// **ولِماذا الجِسمُ حَرفِيٌّ ولَيسَ في القامُوس** — بِسَبَبٍ مَقيسٍ لا
// بِإهمال: يَحمِل `<html>` و`<p>` و`&`، و`value_unsafe_markup` في
// `LocaleValidator` يَرفُض أَيّ قيمَةٍ فيها `< > &`. فَقالَبُ رِسالَةٍ
// كامِلٌ لَيسَ «نَصَّ مِفتاح» بَل مُستَند، وبابُه قَوالِبُ بَريدٍ لا
// قامُوسُ واجِهَة — وذاكَ قَرارٌ آخَر لَه مَوجَتُه.

/// <summary>
/// جِسمُ رِسالَةِ الرَمز — نَصّاً وHTML — ومِفتاحُ عُنوانِها. تَستَعمِلُه
/// كُلُّ قَناةِ بَريدٍ فِعليَّة، ولا تَملِك أَيٌّ مِنها نُسخَةً خاصَّة.
/// </summary>
public static class OtpEmailMessage
{
    /// <summary>مِفتاحُ العُنوان في القامُوس. تُتَرجِمُه القَناةُ
    /// بِالعَرَبِيَّةِ صَراحَةً: الرِسالَةُ تُقرَأ في صُندوقِ بَريدٍ لا في
    /// مُتَصَفِّح، فَلُغَةُ الكوكي لَيسَت لُغَةَ القارِئ.</summary>
    public const string SubjectKey = "auth.email.otp_subject";

    /// <summary>الجِسمُ النَصّيّ (‏<c>text/plain</c>).</summary>
    public static string Text(string code)
        => $"رَمز التَّحَقُّق: {code}\nصالِح لِعَشر دَقائِق. إن لَم تَطلُبه فَتَجاهَل هذِه الرِّسالَة.";

    /// <summary>الجِسمُ الغَنيّ (‏<c>text/html</c>)، بِاتِّجاهٍ عَرَبيّ
    /// وأَرقامٍ لاتينِيَّةٍ مِن اليَسار — الرَمزُ نَفسُه لا يُقلَب.</summary>
    public static string Html(string code)
        => $"""
            <html dir="rtl"><body style="font-family:Tahoma,Arial;line-height:1.6;">
            <p>رَمز التَّحَقُّق الخاصّ بِك:</p>
            <p style="font-size:28px;font-weight:700;letter-spacing:.3em;direction:ltr;">{code}</p>
            <p style="color:#6b7280;font-size:13px;">صالِح لِعَشر دَقائِق. إن لَم تَطلُبه فَتَجاهَل هذِه الرِّسالَة.</p>
            </body></html>
            """;
}
