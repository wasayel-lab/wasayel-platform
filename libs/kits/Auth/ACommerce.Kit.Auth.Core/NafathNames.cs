using System.Text;

namespace ACommerce.Kit.Auth;

/// <summary>
/// <para><b>اِسم عَرض مُشتَقّ مِن رَقم الهُوِيَّة</b> لِمَن يُسَجِّل عَبر
/// نَفاذ. كانَ كُلّ هؤُلاء يَحمِلون الاسم نَفسَه («مُستَخدِم نَفاذ»)
/// فَتَبدو كُلّ شاشَة فيها أَكثَر مِن طَرَف مُكَرَّرَةً: قائِمَة العُروض
/// كُلُّها بِاسم واحِد، وطَرَفا المُحادَثَة بِاسم واحِد.</para>
///
/// <para><b>والاِشتِقاق حَتميّ لا عَشوائيّ</b> — وهذه قاعِدَة في هذا
/// المَشروع لا تَفضيل: نَفس الهُوِيَّة تُعطي نَفس الاسم في كُلّ مَرَّة،
/// وفي كُلّ عَمَلِيَّة، وبَعدَ كُلّ إعادَة تَشغيل. ولِذلِك <b>لا يُستَعمَل
/// <c>string.GetHashCode</c></b>: بَذرَتُه تَتَبَدَّل مَع كُلّ عَمَلِيَّة
/// في dotnet، فَكانَ سَيُعطي اسماً مُختَلِفاً لِنَفس الهُوِيَّة بَعدَ كُلّ
/// إقلاع. البَديل هُنا FNV-1a مَكتوبَة صَراحَةً — ثابِتَة عَبر
/// العَمَلِيّات والمِنَصّات.</para>
///
/// <para><b>وهو اِسم عَرض لِلتَّطوير فَقَط</b>: مُزَوِّد نَفاذ الحَقيقيّ
/// يُعيد الاسم المُوَثَّق مِن الأَحوال المَدَنِيَّة، وحينَها لا مَوضِع
/// لِهذه الدالَّة. لا يُبنى عَلَيها أَيّ قَرار — لا صَلاحِيَّة ولا
/// مُطابَقَة هُوِيَّة.</para>
/// </summary>
public static class NafathNames
{
    /// <summary>أَسماء أُولى — مُذَكَّرَة ومُؤَنَّثَة مَعاً، فَرَقم
    /// الهُوِيَّة لا يَحمِل الجِنس ولا يُشتَقّ مِنه.</summary>
    private static readonly string[] Firsts =
    {
        "مُحَمَّد", "عَبدُالله", "أَحمَد", "خالِد",
        "سُلطان", "فَهد", "نايِف", "تُركي",
        "بَندَر", "ياسِر", "ماجِد", "وَليد",
        "نورَة", "سارَة", "لَطيفَة", "مُنيرَة",
        "هَيفاء", "رَيّا", "جَواهِر", "شَيخَة"
    };

    /// <summary>أَسماء عائِلات شائِعَة.</summary>
    private static readonly string[] Families =
    {
        "العُتَيبي", "القَحطاني", "الغامِدي", "الشَهري",
        "الحَربي", "الدَوسَري", "الزَهراني", "المُطَيري",
        "الشَمري", "البَقَمي", "السُبَيعي", "العَنَزي"
    };

    /// <summary>عَدَد الأَسماء المُمكِنَة — 20 × 12.</summary>
    public static int Combinations => Firsts.Length * Families.Length;

    /// <summary>الاِسم حينَ لا تُعطى هُوِيَّة أَصلاً.</summary>
    public const string Fallback = "مُستَخدِم نَفاذ";

    /// <summary>
    /// اِسم العَرض لِهذه الهُوِيَّة. فارِغ أَو <c>null</c> ←
    /// <see cref="Fallback"/>.
    /// </summary>
    public static string For(string? nationalId)
    {
        if (string.IsNullOrWhiteSpace(nationalId)) return Fallback;

        var h = Fnv1a(nationalId.Trim());

        // شَريحَتان مِن نَفس البَصمَة: الباقي لِلاسم الأَوَّل، وحاصِل
        // القِسمَة لِلعائِلَة — فَلا يَرتَبِط الحَقلان بِبَعضِهِما.
        var first  = Firsts[(int)(h % (uint)Firsts.Length)];
        var family = Families[(int)(h / (uint)Firsts.Length % (uint)Families.Length)];
        return $"{first} {family}";
    }

    /// <summary>FNV-1a ‏32-بِت فَوق بايتات UTF-8. مَكتوبَة هُنا لِأَنّ
    /// الحَتمِيَّة عَبر العَمَلِيّات شَرط لا تُعطيه دَوالّ التَجزِئَة
    /// المَبنيَّة لِلمَجاميع.</summary>
    private static uint Fnv1a(string s)
    {
        var h = 2166136261u;
        foreach (var b in Encoding.UTF8.GetBytes(s))
        {
            h ^= b;
            h *= 16777619u;
        }
        return h;
    }
}
