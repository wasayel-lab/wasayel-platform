namespace ACommerce.Kit.Auth;

/// <summary>خَرقٌ واحِدٌ في طَلَبِ حَذفِ الحِساب. نَفسُ شَكلِ
/// <c>DealCancelViolation</c> و<c>RoleDefinitionViolation</c> حَرفاً
/// (القاعِدَة ٤).</summary>
public sealed record AccountDeletionViolation(string Code, string MessageAr);

/// <summary>
/// <para><b>حَذفُ الحِسابِ داخِلَ التَطبيق — بَوّابَةٌ وأَثَرٌ، كِلاهُما
/// دالَّةٌ نَقِيَّة.</b> لا قاعِدَةَ بَيانات، ولا وَقتٌ يُقرَأُ مِن
/// السّاعَة (الوَقتُ يُمَرَّر)، ولا عَشوائيَّة — نَفسُ عَقدِ
/// <c>DealCancelAuthorization</c>. فَالمَسارُ يُقاسُ كامِلاً بِلا
/// إقلاعِ خادِمٍ ولا كِتابَةِ صَفٍّ واحِد.</para>
///
/// <para><b>المُخالَفَةُ الَّتي كَتَبَت هذا المِلَفّ، مَقيسَةً</b>:
/// شَرطُ المَتجَر ‏5.1.1(v) يوجِبُ حَذفَ الحِسابِ <b>داخِلَ
/// التَطبيق</b>. ونَصُّ المَنَصَّةِ كانَ يَقولُ في مَوضِعَين:
/// «لِحَذف حِسابك بِالكامِل: تَواصَل عَبر صَفحَة الدَّعم»
/// (‏<c>legal.privacy.deletion</c>)، و«ويُمكِنُكَ طَلَبُ حَذفِ
/// حِسابِكَ وبَياناتِكَ بِمُراسَلَتِنا، ويُنَفَّذُ الطَلَبُ خِلالَ
/// ثَلاثينَ يَوماً» (‏<c>platform.privacy.s6_body</c>). و<c>grep</c>
/// عَلى المُستودَعِ كُلِّه عَن مَسارِ حَذفٍ أَعطى <b>مُطابَقَةً
/// واحِدَةً يَتيمَةً هي الجُملَةُ الَّتي تُحيلُ إلى الخارِج</b> — أَي
/// أَنَّ الوُرودَ الوَحيدَ لِعِبارَةِ حَذفِ الحِسابِ كانَ نَصَّ
/// المُخالَفَةِ نَفسَه.</para>
///
/// <para><b>ولِماذا إخفاءُ الهُوِيَّةِ لا مَحوُ الوَثيقَة — وهُوَ
/// قَرارٌ يُعلَنُ لا يُبتَلَع</b>: الوَثيقَةُ مُشارٌ إلَيها مِن
/// الصَفَقاتِ والفَواتيرِ بِمُعَرِّفِها، ومَحوُها يَترُكُ سِجِلّاً
/// مالِيّاً بِطَرَفٍ مَفقود. والمادَّةُ الخامِسَةُ تُجيزُ الاحتِفاظَ
/// صَراحَةً «دونَ إخلالٍ بِما يَقضي بِه نِظامٌ آخَر» — والالتِزامُ
/// المُحاسَبِيُّ مِنها. فَالَّذي يَزولُ <b>الآنَ</b> هُوَ كُلُّ ما
/// يَدُلُّ عَلى الشَخص، ويَبقى الصَفُّ بِلا اسمٍ ولا وَسيلَةِ
/// اتِّصال. <b>وهذا يُقالُ لِلمُستَخدِمِ عَلى الشاشَةِ قَبلَ أَن
/// يُؤَكِّد</b> — وحَذفٌ يُخفي ما يُبقيه يَعِدُ بِما لا يَفي.</para>
///
/// <para><b>وما لَم يُحسَم — يُوقَفُ ويُكتَب</b> (وهُوَ في
/// ‏ADR-030 وفي تَقريرِ المَوجَة): أَمَحوٌ تامٌّ بَعدَ انقِضاءِ
/// المُدَّةِ المُحاسَبِيَّة؟ ومُهلَةُ تَراجُعٍ قَبلَ النَفاذ؟
/// وماذا يَحِلُّ بِإعلاناتِه ومُحادَثاتِه المَنشورَة؟ الثَلاثَةُ
/// تَلمِسُ مالاً وسِجِلّاً، فَلا تُبَتُّ في جَولَةِ تَنفيذ.</para>
///
/// <para><b>دِقَّةٌ ‏2026-10-25 (مُراجَعَةُ تَيّارِ W8-4 الجَولَة ٢؛ يُلحَقُ ولا يُعادُ حَرفٌ فَوقَها)</b>: «يَزولُ الآنَ كُلُّ ما يَدُلُّ عَلى
/// الشَخص، ويَبقى الصَفُّ بِلا اسمٍ ولا وَسيلَةِ اتِّصال» أَعلاه أَوسَعُ مِمّا يَفعَلُه الكود: <see cref="Erase"/> يَمحو وَثيقَةَ
/// <see cref="User"/> وَحدَها، والنُسَخُ خارِجَها — اسمٌ عَلى الصَفقَةِ والمُحادَثَةِ والتَقييم، وإشعاراتٌ في صَناديقِ غَيرِه، ومِفتاحُ رَبطٍ
/// يَبقى يَعمَلُ بِاسمِه — مَعدودَةٌ في <c>AccountDeletionRetentionTests</c> §٣ب (خَصائِصُ الاسمِ المُخَزَّنَة) و§٣ج (كُتّابُ الإشعار)،
/// والنُصوصُ الثَلاثَةُ تَقولُها (الخِيارُ (ب))؛ ومَحوُها (الخِيارُ (أ)) قَرارُ المالِكِ في سِجِلِّه «ب» W8-4 · ١.</para>
///
/// <para><b>‏2026-10-28 (قَرارُ المالِك د56؛ يُلحَقُ ولا يُعادُ حَرفٌ فَوقَه)</b>: «ومِفتاحُ رَبطٍ يَبقى يَعمَلُ بِاسمِه» أَعلاه لَم يَعُد يَصدُق —
/// نُقطَةُ الحَذفِ تُبطِلُ مَفاتيحَه في المُعامَلَةِ نَفسِها (<c>ApiKeyService.RevokeActorKeysAsync</c>، في القالِب لا هُنا: هذِه النَواةُ لا تَعرِفُ
/// وَثيقَةَ المِفتاح)، ومِفتاحٌ صاحِبُه مَحذوفٌ يُرَدُّ عِندَ الاستِعمالِ بِـ<c>ApiKeyRejection.ActorGone</c>؛ ويَبقى اسمُه عَلى الوَثيقَةِ المُبطَلَةِ
/// نُسخَةً ساكِنَةً تَقولُها النُصوصُ في «سِجِلِّ التَدقيقِ ومَفاتيحِ الرَبط».</para>
///
/// <para><b>‏2026-10-29 (قَرارُ المالِك د52 (١) «أ»؛ يُلحَقُ ولا يُعادُ حَرفٌ فَوقَ ما سَبَق)</b>: وَقَعَ الخِيارُ (أ) — «يُمَدُّ الحَذفُ إلى ما يُمكِنُ تَعديلُه».
/// فَنُسَخُ الاسمِ في الصَفَقاتِ والمُحادَثاتِ والتَقييماتِ والعُروضِ والتَذاكِرِ ومَفاتيحِ الرَبطِ والإشعاراتِ المُخَزَّنَةِ يَمحوها القالِبُ
/// (<c>AccountErasure.EraseCopiesAsync</c>) في مُعامَلَةِ النُقطَةِ نَفسِها، ومَعَها عُنوانُ التَوصيلِ وهاتِفُه مِن صَفَقاتٍ بادَرَ بِها؛ وما في سِجِلٍّ لا يُعَدَّلُ
/// بِطَبيعَتِه (مَجرى الأَحداث، وسِجِلُّ التَدقيقِ ويُخفى فيه عِندَ العَرض) تَقولُه النُصوص. و<see cref="Erase"/> باقِيَةٌ عَلى وَثيقَتِها — هذِه النَواةُ لا تَعرِفُ
/// تِلكَ الوَثائِق. ورَمزٌ خامِسٌ <see cref="OpenDeal"/>: صَفقَةٌ جارِيَةٌ تَمنَعُ الحَذفَ قَبلَ أَيِّ مَحو. (‏ADR-045 §٦.)</para>
/// </summary>
public static class AccountDeletion
{
    // ─── مَعجَمُ الرَفضِ المُغلَق ───────────────────────────────────

    /// <summary>لا جَلسَةَ صالِحَة — ولا يُحذَفُ حِسابٌ بِلا صاحِبِه.</summary>
    public const string NotAuthenticated = "not_authenticated";

    /// <summary>لا وَثيقَةَ بِهذا المُعَرِّفِ في هذا المُستَأجِر.</summary>
    public const string UserNotFound = "user_not_found";

    /// <summary>الحِسابُ مَحذوفٌ سَلَفاً — والتِكرارُ لا يُبتَلَعُ
    /// صامِتاً، لِأَنَّ «نَجَحَ» عَن لا شَيءٍ يُخفي عَطَباً في
    /// المَسار.</summary>
    public const string AlreadyDeleted = "already_deleted";

    /// <summary>كَلِمَةُ التَأكيدِ لَم تُطابِق.</summary>
    public const string ConfirmationMismatch = "confirmation_mismatch";

    /// <summary>‏(‏2026-10-29، قَرارُ المالِك د52 (١) «أ») لِلحِسابِ صَفقَةٌ جارِيَة — يُكمِلُها أَو يُلغيها (أَو يَطلُبُ ذلكَ مِن المَتجَر) أَوَّلاً، بَدَلَ أَن يَبقى
    /// طَرَفُها الآخَرُ بِصَفقَةٍ طَرَفُها مَمحُوّ. ما «الجارِيَةُ» يُقَرِّرُه القالِبُ (الَّذي يَعرِفُ الصَفقَة) ويُمَرِّرُ عَدَدَها — هذِه النَواةُ لا تَعرِفُ وَثيقَتَها.</summary>
    public const string OpenDeal = "open_deal";

    /// <summary>‏(‏2026-10-30، الموجَة ١٢ F2 · ٣ — F2B-1؛ تَوصيفُه <c>7c4dad0</c>) لِلحِسابِ رِحلَةٌ جارِيَة — مُطابَقَةُ عَرضٍ فَعّالَةٌ هُوَ سائِقُها أَو صاحِبُ إعلانِها،
    /// ولا صَفقَةَ فيها فَلا يَعُدُّها <see cref="OpenDeal"/>. يُنهيها أَو يُلغيها مِن صَفحَةِ الإعلانِ أَوَّلاً — د52 (١) «حِمايَةً لِلطَرَفِ الَّذي بَدَأَ التَنفيذ» — بَدَلَ أَن
    /// يُسحَبَ الإعلانُ وتَبقى المُطابَقَةُ فَعّالَةً فَيُرَدَّ السائِقُ عَن كُلِّ عَرضٍ جَديد. ما «الجارِيَةُ» يُقَرِّرُه القالِبُ ويُمَرِّرُ عَدَدَها، كَالصَفقَة.</summary>
    public const string OpenTrip = "open_trip";

    /// <summary>المَعجَمُ المُغلَق — سِتَّةٌ لا سابِعَ لَها (‏2026-10-29: الخامِسُ <see cref="OpenDeal"/>، د52؛ ‏2026-10-30: السادِسُ <see cref="OpenTrip"/>، F2B-1).</summary>
    public static readonly IReadOnlyList<string> All =
        new[] { NotAuthenticated, UserNotFound, AlreadyDeleted, ConfirmationMismatch, OpenDeal, OpenTrip };

    public static bool Contains(string code) => All.Contains(code, StringComparer.Ordinal);

    /// <summary>يَرمي عِندَ الخَرق — لِمَواضِعِ التَركيب. نَفسُ حيلَةِ
    /// <c>DealCancelAuthorization.Require</c> حَرفاً.</summary>
    public static string Require(string code)
    {
        if (!Contains(code))
            throw new ArgumentException(
                $"الرَمز «{code}» خارِج مَعجَم AccountDeletion. " +
                $"المَعجَم: {string.Join("، ", All)}.", nameof(code));
        return code;
    }

    /// <summary>الاسمُ الَّذي يَحِلُّ مَحَلَّ اسمِ المُستَخدِمِ بَعدَ
    /// الحَذف. قيمَةٌ مُخَزَّنَةٌ لا نَصُّ واجِهَة — بِنَفسِ دَلالَةِ
    /// <c>User.FullName</c> الافتِراضِيَّةِ المَكتوبَةِ في
    /// <c>User.cs</c> مُنذُ كُتِب.</summary>
    public const string ErasedName = "حِسابٌ مَحذوف";

    // ─── البَوّابَة ────────────────────────────────────────────────

    /// <summary>
    /// <para><c>null</c> يَعني: امضِ. والتَرتيبُ مَقصود — الغِيابُ
    /// أَوَّلاً لِأَنَّه لا يُفشي شَيئاً، ثُمَّ الحالَة، ثُمَّ
    /// التَأكيد.</para>
    ///
    /// <para><b>ولِماذا التَأكيدُ مُقارَنَةٌ نَصِّيَّةٌ لا مُرَبَّعُ
    /// اختِيار</b>: الحَذفُ لا رُجوعَ فيه، وضَغطَةٌ واحِدَةٌ تَقَعُ
    /// سَهواً. وكَلِمَةُ التَأكيدِ <b>تُمَرَّر</b> ولا تُكتَبُ هُنا،
    /// لِتَبقى نَصَّ واجِهَةٍ مِن القامُوس (القاعِدَة ١١) لا
    /// حَرفِيَّةً في بَوّابَة.</para>
    ///
    /// <para><b>‏2026-10-29 (قَرارُ المالِك د52 (١) «أ»؛ يُلحَقُ ولا يُعادُ حَرفٌ فَوقَه)</b>: و<paramref name="openDeals"/> — عَدَدُ صَفَقاتِه الجارِيَةِ
    /// كَما عَدَّها القالِبُ — وَسيطٌ إلزامِيٌّ لا افتِراضِيّ: مُنادٍ يَنسى الصَفَقاتِ لا يُبنى. ومَوضِعُه بَعدَ الحالَةِ وقَبلَ كَلِمَةِ التَأكيد: حالٌ لا حَقل،
    /// فَلا يَكتُبُ المُستَخدِمُ الكَلِمَةَ ثُمَّ يُقالُ لَه إنّ الحَذفَ مُمتَنِع.</para>
    /// <para><b>‏2026-10-30 (الموجَة ١٢ F2 · ٣ — F2B-1؛ يُلحَقُ ولا يُعادُ حَرفٌ فَوقَه)</b>: و<paramref name="openTrips"/> — عَدَدُ رِحلاتِه الجارِيَةِ كَما عَدَّها القالِبُ
    /// — إلزامِيٌّ كَالصَفَقات، ومَوضِعُه بَعدَها: حالٌ ثانِيَةٌ قَبلَ الحَقل، والرَدُّ بِأَوَّلِ خَرقٍ (‏ADR-038).</para>
    /// </summary>
    public static AccountDeletionViolation? Validate(
        User? user, int openDeals, int openTrips, string? typedConfirmation, string expectedConfirmation)
    {
        if (user is null)
            return new(UserNotFound, "لا وَثيقَةَ مُستَخدِمٍ بِهذا المُعَرِّف.");

        if (user.DeletedAt is not null)
            return new(AlreadyDeleted, "الحِسابُ مَحذوفٌ سَلَفاً — لا شَيءَ يُحذَف.");

        if (openDeals > 0)
            return new(OpenDeal, "لِلحِسابِ صَفقَةٌ جارِيَة — تُكمَلُ أَو تُلغى أَوَّلاً، ولَم يُحذَف شَيء.");

        if (openTrips > 0)
            return new(OpenTrip, "لِلحِسابِ رِحلَةٌ جارِيَة — تُنهى أَو تُلغى أَوَّلاً، ولَم يُحذَف شَيء.");

        if (!string.Equals((typedConfirmation ?? "").Trim(), expectedConfirmation,
                StringComparison.Ordinal))
            return new(ConfirmationMismatch,
                "كَلِمَةُ التَأكيدِ لَم تُطابِق — ولَم يُحذَف شَيء.");

        return null;
    }

    public static bool IsAllowed(User? user, int openDeals, int openTrips, string? typed, string expected) =>
        Validate(user, openDeals, openTrips, typed, expected) is null;

    // ─── الأَثَر ───────────────────────────────────────────────────

    /// <summary>
    /// <para><b>يُزيلُ كُلَّ ما يَدُلُّ عَلى الشَخص، ويَترُكُ
    /// الصَفَّ.</b> دالَّةٌ تُعَدِّلُ الوَثيقَةَ المُمَرَّرَةَ وتُرجِعُها
    /// — والوَقتُ وَسيطٌ لا نِداءٌ لِلسّاعَة، فَالاختِبارُ حَتمِيّ.</para>
    ///
    /// <para><b>وكُلُّ حَقلٍ يُصَفَّرُ هُنا مَعدودٌ في اختِبار</b>:
    /// حَقلٌ يُضافُ إلى <see cref="User"/> ولا يُصَفَّرُ هُنا
    /// <b>يُمسَك</b> — وإلّا لَتَسَرَّبَ بَيانٌ شَخصِيٌّ جَديدٌ عَبرَ
    /// حَذفٍ يَظُنُّ صاحِبُه أَنَّه تامّ.</para>
    ///
    /// <para><b>دِقَّةٌ ‏2026-10-25 (مُراجَعَةُ تَيّارِ W8-4 الجَولَة ٢؛ يُلحَقُ ولا يُعادُ حَرفٌ فَوقَها)</b>: «يُزيلُ كُلَّ ما يَدُلُّ عَلى الشَخص»
    /// أَدَقُّه: يُصَفِّرُ حُقولَ <see cref="User"/> هذِه وَحدَها. ونُسَخُ الاسمِ والهاتِفِ والبَريدِ في الوَثائِقِ الأُخرى لا يَمَسُّها — جَردُها في
    /// <c>AccountDeletionRetentionTests</c> §٣ب و§٣ج، وما يَبقى يُقالُ في نُصوصِ الحَذف؛ ومَحوُها قَرارُ المالِك («ب» W8-4 · ١).</para>
    /// </summary>
    public static User Erase(User user, DateTime at)
    {
        user.FullName = ErasedName;
        user.Phone = "";
        user.Email = "";
        user.NationalId = null;
        user.AvatarUrl = null;
        user.PhoneVerified = false;
        user.EmailVerified = false;
        user.ActiveRole = "";
        user.AttributesJson = new Dictionary<string, string>();
        user.RoleAttributesJson = new Dictionary<string, Dictionary<string, string>>();
        user.PushSubscriptions = new List<PushSubscription>();
        user.AnchorLat = 0;
        user.AnchorLng = 0;
        user.RadiusKm = 0;
        user.DeletedAt = at;
        user.UpdatedAt = at;
        // ‏(‏2026-10-28، قَرارُ المالِك د28) يُرفَعُ ولا يُمحى: كُلُّ رَمزٍ صَدَرَ قَبلَ الحَذفِ يَسقُطُ عِندَ بَوّابَةِ الجَلسَة، ولَو عَلى جِهازٍ آخَر.
        user.SessionVersion++;
        return user;
    }
}
