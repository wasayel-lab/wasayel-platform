namespace ACommerce.Kit.Subscriptions;

// ═══ رِباطُ باقَةِ المَنَصَّةِ بِخُطَّةِ PayPal ═════════════════════════
//
// **العِلَّةُ الَّتي كَتَبَت هذا المِلَفّ**: كانَ `paypalPlanId` يَسكُن
// في `*.plan.json` **مَورِداً مُضَمَّناً** — يُقرَأُ ولا يُكتَب. فَخُطوَةُ
// «ضَع المُعَرِّفَ في تَعريفِ الباقَة» كانَت **تَحريرَ مِلَفٍّ ودَفعاً
// ونَشراً**: إصداراً كامِلاً مُقابِلَ سِلسِلَةٍ واحِدَة.
//
// **ولِماذا وَثيقَةٌ عَلى الباقَةِ لا حَقلٌ على وَثيقَةِ المُستَأجِر**:
// الخُطَّةُ **خَصيصَةُ الباقَة** لا خَصيصَةُ مَتجَر (‏ADR-004 §٣-ج) —
// كُلُّ مَن يَشتَري «الباقَةَ الفُلانِيَّة» يَشتَري نَفسَ خُطَّةِ
// PayPal. ووَضعُها على المُستَأجِرِ يُنتِج نُسخَةً لِكُلّ مَتجَرٍ
// تَنجَرِف. فَمُعَرِّفُ هذِه الوَثيقَةِ **سلاجُ الباقَة**، ولا احتِمالَ
// لِوَثيقَتَينِ لِباقَةٍ واحِدَة.
//
// **والمِلَفُّ يَبقى ولا يُلغى**: مَن حَرَّرَ `paypalPlanId` في
// التَعريفِ يَعمَل كَما كان. والوَثيقَةُ **تَفوز عِندَ وُجودِها**
// لِأَنَّها الأَحدَثُ قَصداً — وهي الَّتي تُكتَب مِن الشاشَة.

/// <summary>
/// <para><b>خُطَّةُ PayPal لِباقَةِ مَنَصَّةٍ واحِدَة</b> — وَثيقَةٌ
/// <c>SingleTenanted</c> كَـ<see cref="TenantPlan"/> ولِنَفسِ السَبَب:
/// تُقرَأُ <b>قَبلَ</b> أَن يُعرَفَ مُستَأجِرُ الطَلَب، وباقَةُ
/// المَنَصَّةِ لَيسَت مِلكَ مُستَأجِر.</para>
/// </summary>
public sealed class PlatformPlanPayPal
{
    /// <summary>سلاجُ باقَةِ المَنَصَّة — المِفتاحُ الأَوَّليّ.</summary>
    public string Id { get; set; } = "";

    /// <summary>مُنتَجُ الكاتالوجِ كَما وَلَّدَتهُ PayPal
    /// (‏<c>PROD-…</c>). <b>يُخَزَّن ولا يُهمَل</b>: خُطَّةٌ ثانِيَةٌ
    /// غَداً تُعَلَّقُ عَلَيه بَدَلَ مُنتَجٍ ثانٍ يَتيم.</summary>
    public string ProductId { get; set; } = "";

    /// <summary>مُعَرِّفُ الخُطَّة (‏<c>P-…</c>) — <b>وهُوَ المَقصودُ
    /// كُلُّه</b>: ما يُمَرَّرُ إلى إنشاءِ الاشتِراك.</summary>
    public string PlanId { get; set; } = "";

    // ═══ نُسخَةٌ مِمّا أُرسِلَ — لِلعَرضِ والتَدقيقِ لا لِلقَرار ═══════
    //
    // **والسِعرُ الحاكِمُ سِعرُ PayPal لا هذا**: هذِه لَقطَةُ ما
    // أُرسِلَ يَومَ الإنشاء، تُعرَض في الشاشَةِ لِيَعرِفَ المُشرِفُ
    // ماذا أَنشَأَ. ولَو غُيِّرَ السِعرُ مِن لَوحَةِ PayPal لاحِقاً
    // بَقِيَت هذِه كَما هي — **ولِذلك لا يَقرَؤُها قَرار**، فَمَصدَرُ
    // الحَقيقَةِ لِلخَصمِ خُطَّةُ PayPal نَفسُها (نَفسُ حُجَّةِ
    // `MonthlyAmountSar` الَّتي لا تُرسَل عِندَ إنشاءِ الاشتِراك).

    public string Name { get; set; } = "";
    public decimal Amount { get; set; }
    public string Currency { get; set; } = "";
    public string IntervalUnit { get; set; } = "";

    /// <summary>مَن أَنشَأَها ومَتى — لِلتَدقيقِ لا لِلقَرار.</summary>
    public string CreatedBy { get; set; } = "";
    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;
}

/// <summary>
/// <para><b>«أَيُّ خُطَّةٍ لِهذِه الباقَة؟» — دالَّةٌ نَقِيَّةٌ واحِدَة.</b>
/// مَصدَرانِ لِلقيمَة (المِلَفُّ المُضَمَّنُ والوَثيقَةُ المَكتوبَةُ مِن
/// الشاشَة)، و<b>مَصدَرانِ بِلا قاعِدَةِ تَرجيحٍ مَكتوبَةٍ في مَوضِعٍ
/// واحِدٍ يَنجَرِفان</b>: الشاشَةُ تُظهِر واحِداً والنُقطَةُ تُرسِل
/// الآخَر (القاعِدَة ٢).</para>
/// </summary>
public static class PlatformPlanPayPalBinding
{
    /// <summary>
    /// <para><b>الوَثيقَةُ تَفوز، ثُمَّ المِلَفّ، ثُمَّ <c>null</c>.</b>
    /// و<c>null</c> تَعني <b>لا بِطاقَةَ PayPal إطلاقاً</b> — لا زِرَّ
    /// يَقول «قَريباً» (القاعِدَة ١٢).</para>
    ///
    /// <para><b>ولِماذا الوَثيقَةُ أَوَّلاً</b>: هي الأَحدَثُ قَصداً —
    /// تُكتَب بِنَقرَةِ مُشرِفٍ اليَوم، والمِلَفُّ يُحَرَّرُ في إصدار.
    /// فَلَو فازَ المِلَفُّ لَكانَت الشاشَةُ تَكتُب ما لا يُقرَأ، وذاكَ
    /// أَسوَأُ مِن أَلّا تَكتُبَ شَيئاً.</para>
    /// </summary>
    public static string? Resolve(PlatformPlanDefinition? definition, PlatformPlanPayPal? bound)
        => !string.IsNullOrWhiteSpace(bound?.PlanId) ? bound!.PlanId.Trim()
         : !string.IsNullOrWhiteSpace(definition?.PayPalPlanId) ? definition!.PayPalPlanId!.Trim()
         : null;
}
