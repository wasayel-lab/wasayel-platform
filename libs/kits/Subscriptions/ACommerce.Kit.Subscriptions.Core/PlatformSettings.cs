namespace ACommerce.Kit.Subscriptions;

/// <summary>
/// <para><b>إعداداتُ المَنَصَّة — وَثيقَةٌ واحِدَةٌ لا أَكثَر.</b>
/// مُعَرِّفُها ثابِتٌ (<see cref="SingletonId"/>) فَلا تَصير وَثيقَتَين
/// تَنجَرِفان، وهي <c>SingleTenanted</c> كَسِجِلّ المُستَأجِرين: إعدادُ
/// المَنَصَّةِ لَيسَ مِلكَ مُستَأجِر.</para>
///
/// <para><b>ولِماذا وَثيقَةٌ لا حَرفِيَّةٌ في الكود</b>: نَصُّ تَعليمات
/// التَحويل يَحمِل <b>آيبانَ وَسايِل</b> — يَتَغَيَّر بِلا نَشر،
/// وحَرفِيَّةٌ في الكود تَجعَل تَغييرَ رَقمِ حِسابٍ **إصداراً**. وهي
/// نَفسُ الحُجَّة الَّتي كَتَبَت حَقلَ التَحويل في وَثيقَة المُستَأجِر
/// أَمس — والفَرقُ أَنّ القابِضَ تَغَيَّر: وَسايِل لا التاجِر.</para>
/// </summary>
public sealed class PlatformSettings
{
    public const string SingletonId = "platform";

    public string Id { get; set; } = SingletonId;

    /// <summary>
    /// <para><b>تَعليماتُ التَحويلِ إلى وَسايِل</b> — نَصٌّ حُرٌّ
    /// يُحَرِّرُه مُشرِفُ المَنَصَّة ويَراه رائِدُ الأَعمال في
    /// الاستوديو: اسمُ الحِساب، والآيبان، وما يُكتَب في خانَة الغَرَض.</para>
    ///
    /// <para><b>وفَراغُه لَيسَ عَطباً</b>: الاستوديو يَعرِض بَدَلَه سَطراً
    /// يَقول إنَّها لَم تُسَجَّل بَعد، فَلا يَظُنُّ صاحِبُ المَتجَر أَنّ
    /// شاشَتَه مَكسورَة.</para>
    /// </summary>
    public string TransferInstructions { get; set; } = "";

    public string UpdatedBy { get; set; } = "";
    public DateTime UpdatedAt { get; set; } = DateTime.UtcNow;
}
