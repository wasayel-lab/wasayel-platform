namespace ACommerce.Kit.Subscriptions;

// ═══ دَفعَةٌ مُعَلَّقَة — ما وَعَدَ بِه المُشرِفُ قَبلَ أَن يَصِلَ المال ══
//
// **العِلَّةُ الَّتي كَتَبَت هذا المِلَفّ (‏ADR-006)**: مَسارُ الطَلَبات
// يُرسِلُ المَبلَغَ لَحظَةَ الطَلَب، **ولا خُطَّةَ عِندَ PayPal تَحمِلُ
// المُدَّة**. فَـ«كَم يَوماً تُمَدَّدُ الباقَةُ عِندَ وُصولِ المال؟»
// سُؤالٌ **لا تُجيبُ عَنه رِسالَةُ PayPal إطلاقاً** — يُجيبُ عَنه
// المُشرِفُ يَومَ يُنشِئ الرابِط، ويُخَزَّنُ جَوابُه هُنا.
//
// **ووَثيقَةٌ إلزامِيَّةٌ لا تَرَف، ولِسَبَبٍ ثانٍ مَقيس**: لَم توجَد
// جُملَةٌ رَسمِيَّةٌ تَنُصُّ على انتِقالِ `custom_id` مِن
// `purchase_unit` إلى **مَورِدِ الالتِقاط**؛ عَيِّنَةُ Trustly
// الرَسمِيَّةُ تُظهِرُه في `PENDING`، وعَيِّنَتا `COMPLETED` تَخلُوانِ
// مِنه. فَهذِه الوَثيقَةُ هي المَسارُ الاحتِياطيُّ عَبرَ
// `supplementary_data.related_ids.order_id`، وهي أَيضاً ما يَجعَل
// صَفحَةَ العَودَةِ قادِرَةً على قَولِ شَيء. **ومَن حَذَفَها لاحِقاً
// ظَنّاً أَنَّها زائِدَة كَسَرَ المَسار.**

/// <summary>حالاتُ وَثيقَةِ الطَلَبِ كَما يَقرَؤُها القامُوسُ
/// والشاشَة — <b>ومَعجَمُها في
/// <c>ACommerce.Kit.Payments.Providers.PayPal.PayPalOrderStatuses</c></b>،
/// فَلا تُنسَخ هُنا. وهذا الصِنفُ يَحمِل الوَثيقَةَ وَحدَها: سَهمُ
/// الاعتِمادِ يَمشي مِن المُزَوِّدِ إلى هُنا لا العَكس.</summary>
/// <remarks>
/// <para><b>ومُعَرِّفُها <c>مَرجِعُنا</c> لا مُعَرِّفُ الطَلَبِ عِندَ
/// PayPal — ويُقالُ لِماذا</b>: مُعَرِّفُ PayPal لا يُعرَف إلّا
/// <b>بَعدَ</b> النِداء، بَينَما <c>custom_id</c> يُرسَل <b>فيه</b>.
/// فَمِفتاحٌ هُوَ مُعَرِّفُ PayPal يَجعَل الرِباطَ مُستَحيلاً في
/// الاتِّجاهِ الَّذي نَحتاجُه فِعلاً: مِن رِسالَةِ الالتِقاطِ إلى
/// وَثيقَتِنا. والمَرجِعُ حَتميٌّ مُشتَقٌّ مِن مُدخَلاتِ الطَلَب، فَـ
/// <b>نَقرَتانِ تُعطِيانِ وَثيقَةً واحِدَةً</b> بِمِفتاحِ الوَثيقَةِ
/// نَفسِه لا بِفَحصِ وُجودٍ في التَطبيق.</para>
///
/// <para><b>و<c>SingleTenanted</c></b> كَـ<see cref="TenantPlan"/>
/// ولِنَفسِ السَبَبِ حَرفاً: تُقرَأُ وتُكتَبُ في نُقطَةٍ <b>بِلا
/// مُستَأجِرٍ مَحلول</b> (‏<c>api</c> مَحجوزَةٌ في وَسيطِ المُستَأجِر)،
/// وجَلسَةٌ بِسلاجٍ عَلَيها تَكتُب في إيجارٍ لا يُقرَأُ مِنه أَبَداً.</para>
/// </remarks>
public sealed class PayPalOrderRecord
{
    /// <summary><b>مَرجِعُنا</b> — المِفتاحُ الأَوَّليّ، وهُوَ ما
    /// يُرسَل في <c>custom_id</c> و<c>reference_id</c> ويَعودُ بِه كُلُّ
    /// حَدَث.</summary>
    public string Id { get; set; } = "";

    /// <summary>سلاجُ المَتجَرِ الَّذي تُمَدَّدُ باقَتُه.</summary>
    public string TenantSlug { get; set; } = "";

    /// <summary>سلاجُ الباقَةِ وَقتَ الإنشاء — <b>لَقطَةٌ لِلتَدقيقِ لا
    /// قَرار</b>: التَمديدُ يُحَرِّكُ تاريخَ وَثيقَةِ المَتجَرِ أَيّاً
    /// كانَت باقَتُها يَومَ الحَدَث.</summary>
    public string PlanId { get; set; } = "";

    /// <summary>المَبلَغُ المُرسَل — <b>ويُقارَنُ بِما يَصِل</b>.
    /// ودَفعٌ بِمَبلَغٍ أَقَلَّ لا يُمَدِّد.</summary>
    public decimal Amount { get; set; }

    /// <summary>عُملَةُ الطَلَب — تُقارَنُ كَذلك.</summary>
    public string Currency { get; set; } = "";

    /// <summary><b>كَم يَوماً تُمَدَّدُ الباقَةُ عِندَ وُصولِ المال.</b>
    /// قَرارُ المُشرِفِ يَومَ أَنشَأَ الرابِط، <b>ولا يُشتَقُّ يَومَ
    /// الحَدَثِ ولا يُخترَع</b>.</summary>
    public int Days { get; set; }

    /// <summary>ما يَراهُ الدافِعُ على صَفحَةِ PayPal — لِلعَرضِ
    /// والتَدقيق.</summary>
    public string Description { get; set; } = "";

    /// <summary>مُعَرِّفُ الطَلَبِ كَما رَدَّتهُ PayPal — <b>الجِسرُ
    /// الاحتِياطيّ</b> حينَ يَصِل الالتِقاطُ بِلا <c>custom_id</c>.</summary>
    public string OrderId { get; set; } = "";

    /// <summary>مُعَرِّفُ الالتِقاط — <b>المِفتاحُ الوَحيدُ الصالِحُ
    /// عَبرَ دَورَةِ الحَياةِ كُلِّها</b>: الاستِردادُ والعَكسُ
    /// يَصِلانِ بِـ<c>links[rel=up]</c> لا بِمَرجِعِنا. واحفَظهُ أَو
    /// تَعَذَّرَ الاستِردادُ لاحِقاً.</summary>
    public string? CaptureId { get; set; }

    /// <summary><b>رابِطُ الصَفحَةِ المُستَضافَة</b> — يَنسَخُه المُشرِفُ
    /// ويُرسِلُه، ويَراهُ رائِدُ الأَعمالِ في لافِتَةِ الاستوديو.
    /// <b>يُخَزَّن لِأَنّ الطَرَفَينِ يَحتاجانِه</b>، ولَو بَقِيَ في
    /// صَفحَةِ نَتيجَةٍ واحِدَةٍ لَضاعَ بِتَحديثِ الصَفحَة.</summary>
    public string? ApproveUrl { get; set; }

    /// <summary>مِن <c>PayPalOrderStatuses</c> حَصراً. نَصٌّ لا تَعداد:
    /// الوَثيقَةُ تَعيشُ أَطوَلَ مِن أَسماءِ أَعضاءِ تَعدادٍ في كود.</summary>
    public string Status { get; set; } = "created";

    /// <summary>‏<c>status_details.reason</c> كَما وَصَل — <b>يُعرَض ولا
    /// يُقَرِّر</b>. وثَلاثَةٌ مِنه واقِعِيَّةٌ لِتاجِرٍ سُعوديٍّ حَديثِ
    /// الحِساب: <c>UNILATERAL</c>، و
    /// <c>RECEIVING_PREFERENCE_MANDATES_MANUAL_ACTION</c>، و
    /// <c>PENDING_REVIEW</c>.</summary>
    public string? StatusReason { get; set; }

    /// <summary>صافي ما وَصَلَ الحِسابَ بَعدَ الرُسوم كَما قالَتهُ PayPal
    /// — <b>ولا يُشتَقُّ مِن <c>Amount</c> بِأَيّ حِسابٍ مَحَلِّيّ</b>.
    /// يُسَجَّلُ وَقتَ الالتِقاطِ أَو يَضيع.</summary>
    public string? NetAmount { get; set; }

    /// <summary>مَن أَنشَأَه — لِلتَدقيقِ لا لِلقَرار.</summary>
    public string CreatedBy { get; set; } = "";

    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;

    /// <summary>مَتى تَغَيَّرَت الحالَةُ آخِرَ مَرَّة.</summary>
    public DateTime At { get; set; } = DateTime.UtcNow;
}
