namespace ACommerce.Kit.Subscriptions;

// ═══ مُعامَلَةُ Paddle المُعَلَّقَة — ما وَعَدَ بِه المُشرِفُ قَبلَ المال ══
//
// **العِلَّةُ نَفسُها الَّتي كَتَبَت `PayPalOrderRecord` حَرفاً**:
// رِسالَةُ المُزَوِّدِ **لا تَقول كَم يَوماً تُمَدَّدُ الباقَة**.
// يُجيبُ عَن ذلك المُشرِفُ يَومَ يُنشِئ الرابِط، ويُخَزَّنُ جَوابُه
// هُنا. ومَن حَذَفَها ظَنّاً أَنَّها زائِدَة كَسَرَ المَسار.
//
// ═══ ولِماذا وَثيقَةٌ ثانِيَةٌ لا حَقلُ «مُزَوِّد» على الأولى ═════════
//
// السُؤالُ صَحيحٌ ويَستَحِقّ جَواباً مَكتوباً (القاعِدَة ١):
//
// **١) مِفتاحُ Marten هُوَ اسمُ الصِنف.** ضَمُّ المُزَوِّدَينِ في
// وَثيقَةٍ واحِدَةٍ يَعني **إعادَةَ تَسمِيَةِ صِنفٍ حَيٍّ في الإنتاج**
// — أَي جَدوَلاً جَديداً وصُفوفاً يَتيمَةً في القَديم. وهذا ثَمَنٌ
// **مَقيسٌ لا مَظنون**، ويُدفَع مُقابِلَ تَسمِيَةٍ أَجمَل لا مُقابِلَ
// سُلوك.
//
// **٢) الحُقولُ لَيسَت واحِدَة.** ‏PayPal تَحمِل `CaptureId` (مِفتاحُ
// الاستِردادِ الوَحيدُ عِندَها) وخُطوَةَ التِقاطٍ مُنفَصِلَةً بِزِرٍّ
// يَدَويّ. و‏Paddle **لا التِقاطَ فيها إطلاقاً**: الدافِعُ يَدفَع
// فَتَكتَمِل المُعامَلَة. فَحَقلٌ يَبقى فارِغاً أَبَداً في نِصفِ
// الصُفوفِ لَيسَ تَوحيداً بَل تَعايُشاً.
//
// **٣) وما يَجِبُ أَن يَكونَ واحِداً هُوَ واحِدٌ فِعلاً**: تَحريكُ
// `TenantPlan.ExpiresAt` وسِجِلُّ مَرَّة-واحِدَة
// (`PayPalWebhookRecord`) وسِجِلُّ التَدقيق — **باعِثُ تَمديدٍ واحِدٌ
// يَمُرُّ بِه المُزَوِّدان** (القاعِدَة ٨). وهذِه الوَثيقَةُ سِجِلُّ
// **وَعدٍ** لا باعِثُ تَمديد.

/// <summary>
/// <para><b>مُعامَلَةُ دَفعٍ واحِدَةٌ عِندَ Paddle</b> —
/// <c>SingleTenanted</c> كَـ<see cref="TenantPlan"/> ولِنَفسِ السَبَبِ
/// حَرفاً: تُقرَأُ وتُكتَبُ في نُقطَةٍ <b>بِلا مُستَأجِرٍ مَحلول</b>
/// (‏<c>api</c> مَحجوزَةٌ في وَسيطِ المُستَأجِر)، وجَلسَةٌ بِسلاجٍ
/// عَلَيها تَكتُب في إيجارٍ لا يُقرَأُ مِنه أَبَداً.</para>
/// </summary>
public sealed class PaddleTransactionRecord
{
    /// <summary><b>مَرجِعُنا</b> — المِفتاحُ الأَوَّليّ، وهُوَ ما
    /// يُرسَل في <c>custom_data</c> ويَعودُ بِه حَدَثُ الاكتِمال.</summary>
    public string Id { get; set; } = "";

    /// <summary>سلاجُ المَتجَرِ الَّذي تُمَدَّدُ باقَتُه.</summary>
    public string TenantSlug { get; set; } = "";

    /// <summary>سلاجُ الباقَةِ وَقتَ الإنشاء — <b>لَقطَةٌ لِلتَدقيقِ لا
    /// قَرار</b>.</summary>
    public string PlanId { get; set; } = "";

    /// <summary>المَبلَغُ كَما كَتَبَهُ المُشرِف — <b>لِلعَرضِ
    /// وَحدَه</b>. والمُقارَنَةُ تَقَعُ على
    /// <see cref="AmountMinor"/>.</summary>
    public decimal Amount { get; set; }

    /// <summary>
    /// <para><b>المَبلَغُ بِأَصغَرِ وَحدَةٍ نَصّاً — وهُوَ بِعَينِه ما
    /// أُرسِلَ إلى Paddle، وهُوَ بِعَينِه ما يُقارَنُ بِالواصِل.</b></para>
    ///
    /// <para><b>ولِذلك يُخَزَّنُ ولا يُشتَقُّ عِندَ المُقارَنَة</b>:
    /// الاشتِقاقُ وَقتَ الحَدَثِ يَحتاج أُسَّ العُملَةِ ثانِيَةً،
    /// و<b>تَعريفانِ لِقيمَةٍ واحِدَةٍ يَنجَرِفان</b> — فَيُقبَضُ المالُ
    /// ولا تُمَدَّدُ الباقَة، صامِتاً.</para>
    /// </summary>
    public string AmountMinor { get; set; } = "";

    /// <summary>عُملَةُ المُعامَلَة — تُقارَنُ كَذلك.</summary>
    public string Currency { get; set; } = "";

    /// <summary><b>كَم يَوماً تُمَدَّدُ الباقَةُ عِندَ وُصولِ المال.</b>
    /// قَرارُ المُشرِفِ يَومَ أَنشَأَ الرابِط، <b>ولا يُشتَقُّ يَومَ
    /// الحَدَثِ ولا يُخترَع</b>.</summary>
    public int Days { get; set; }

    /// <summary>ما يَراهُ الدافِعُ على صَفحَةِ الدَفع.</summary>
    public string Description { get; set; } = "";

    /// <summary>
    /// <para>مُعَرِّفُ المُعامَلَةِ عِندَ Paddle (<c>txn_…</c>) —
    /// <b>الجِسرُ الوَحيد</b> حينَ يَصِلُ حَدَثٌ بِلا
    /// <c>custom_data</c>، وهُوَ حالُ أَحداثِ التَسوِيَةِ كُلِّها.
    /// و<b>«احتِياطيّ» كانَت تَسمِيَةً تُهَوِّنُه</b>: بِدونِه لا
    /// يُسحَبُ استِردادٌ أَبَداً.</para>
    ///
    /// <para><b>ويُكتَبُ مَرَّتَين لا مَرَّةً، ولِكُلٍّ مَعنى</b>:
    /// عِندَ الإنشاءِ يَحمِل ما رَدَّته Paddle لِآخِرِ نَقرَة،
    /// و<b>عِندَ التَمديدِ يُثَبَّتُ على المُعامَلَةِ الَّتي دَفَعَت
    /// فِعلاً</b> — ونَقرَتانِ تُنشِئانِ مُعامَلَتَينِ عِندَ Paddle
    /// ووَثيقَةً واحِدَةً عِندَنا، فَلَو بَقِيَ الأَوَّلُ لَبَحَثَ
    /// الاستِردادُ عَن مُعامَلَةٍ لَم تَدفَع.
    /// (‏<c>PaddleBillingPolicy.Apply</c>.)</para>
    /// </summary>
    public string TransactionId { get; set; } = "";

    /// <summary>مُعَرِّفُ الاشتِراكِ إن وُلِدَ مِنها واحِدٌ عِندَ
    /// Paddle — <b>يُسَجَّل ولا يُقَرِّر</b>: مَسارُنا مُعامَلَةٌ
    /// واحِدَةٌ لا اشتِراكٌ مُتَكَرِّر.</summary>
    public string? SubscriptionId { get; set; }

    /// <summary><b>رابِطُ الدَفع</b> — يَنسَخُه المُشرِفُ، ويَراهُ
    /// رائِدُ الأَعمالِ في لافِتَةِ الاستوديو. <b>يُخَزَّن لِأَنّ
    /// الطَرَفَينِ يَحتاجانِه</b>.</summary>
    public string? CheckoutUrl { get; set; }

    /// <summary>مِن <c>PaddleTransactionStatuses</c> حَصراً. نَصٌّ لا
    /// تَعداد: الوَثيقَةُ تَعيشُ أَطوَلَ مِن أَسماءِ أَعضاءِ تَعدادٍ في
    /// كود.</summary>
    public string Status { get; set; } = "created";

    /// <summary>آخِرُ حالَةٍ وَصَلَت مِن Paddle كَما هي — <b>تُعرَض ولا
    /// تُقَرِّر</b>. تُقرَأُ حينَ يُسأَل «لِماذا لَم يُمَدَّد؟».</summary>
    public string? ProviderStatus { get; set; }

    /// <summary>مَن أَنشَأَها — لِلتَدقيقِ لا لِلقَرار.</summary>
    public string CreatedBy { get; set; } = "";

    public DateTime CreatedAt { get; set; } = DateTime.UtcNow;

    /// <summary>مَتى تَغَيَّرَت الحالَةُ آخِرَ مَرَّة.</summary>
    public DateTime At { get; set; } = DateTime.UtcNow;
}
