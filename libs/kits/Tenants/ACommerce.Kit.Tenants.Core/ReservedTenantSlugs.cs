namespace ACommerce.Kit.Tenants;

/// <summary>
/// <para><b>الأَسماءُ الَّتي لا يَجوزُ أَن تَكونَ سلاجَ مَتجَر —
/// مَصدَرٌ واحِدٌ يَقرَؤُه المُنشِئُ والوَسيطُ والزاحِف.</b></para>
///
/// <para><b>العِلَّةُ المَقيسَةُ الَّتي أَنشَأَت هذا المِلَفّ</b>:
/// كانَت القائِمَةُ في <c>TenantResolverMiddleware.ReservedPaths</c>
/// <c>internal</c> — <b>ومُستَهلِكُها الوَحيدُ الوَسيط</b>. فَـ
/// <c>TenantFromAnalysisFactory.ValidateSlugAsync</c> كانَ يَفحَصُ
/// <b>الشَكلَ والتَفَرُّدَ ولا يَعرِفُها</b>: مَتجَرٌ سلاجُه
/// <c>pricing</c> أَو <c>terms</c> أَو <c>contact</c>
/// <b>يُنشَأُ بِنَجاح ثُمَّ لا يُحَلُّ أَبَداً</b> — واجِهَةُ
/// مَتجَرٍ لا تُبلَغ، بِلا رِسالَةِ خَطَإٍ ولا سَطرِ لوغ. وذاكَ
/// أَسوَأُ مِن رَفضٍ صَريح: صاحِبُه يَظُنُّ أَنَّه بَنى.</para>
///
/// <para><b>وكانَت هُناكَ قائِمَةٌ ثانِيَةٌ تَنجَرِف</b>:
/// <c>SeoDocuments</c> تَحمِلُ عَشرَةَ أَسماءٍ لا تَحمِلُ فيها
/// <c>terms</c> ولا <c>billing</c> ولا إخوانَهُما — فَمَتجَرٌ
/// سلاجُه <c>terms</c> كانَ <b>يُدرَجُ في خَريطَةِ المَوقِعِ
/// لِلزاحِفِ وهُوَ لا يُفتَحُ أَصلاً</b>. وقائِمَتانِ لِمَعنىً
/// واحِدٍ تَنجَرِفان (القاعِدَة ٢)، والانجِرافُ هذا كانَ
/// <b>واقِعاً لا مُحتَمَلاً</b>.</para>
///
/// <para><b>وثَلاثَةُ مُستَهلِكينَ لا اثنان</b> (القاعِدَة ١):
/// الوَسيطُ (<c>SlugFromPath</c>)، والمُنشِئُ
/// (<c>ValidateSlugAsync</c>)، و<c>SeoDocuments.IsPublic</c>.</para>
/// </summary>
public static class ReservedTenantSlugs
{
    /// <summary>
    /// <para><b>المَعجَمُ المُغلَق.</b> والمُقارَنَةُ بِتَجاهُلِ
    /// حالَةِ الأَحرُف: السلاجُ يُطَبَّعُ صَغيراً عِندَ الحَلّ،
    /// و<c>Terms</c> ليسَ بابَاً خَلفِيّاً لِـ<c>terms</c>.</para>
    /// </summary>
    public static readonly IReadOnlySet<string> All =
        new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            // ─── لَوحاتُ المَنَصَّةِ وبِنيَةُ Blazor التَحتِيَّة ─────
            "admin", "_admin", "_blazor", "_framework", "_content",
            "css", "js", "lib", "favicon.ico", "health", "realtime",

            // ─── الاستوديو — واجِهَةُ رائِدِ الأَعمال ────────────────
            //
            // **كانَ في قائِمَةِ `SeoDocuments` ولَيسَ في قائِمَةِ
            // الوَسيط**، وهذا بِعَينِه الانجِرافُ الَّذي وَحَّدَه هذا
            // المِلَفّ. **والأَثَرُ على الحَلِّ صِفر**: كانَ الوَسيطُ
            // يَستَعلِمُ عَن مُستَأجِرٍ اسمُه «‏studio» عِندَ كُلِّ
            // زِيارَةِ استوديو فَيَفشَل — و«استِعلامٌ يَفشَل» صارَ «لا
            // استِعلام»، والقيمَةُ المُشتَقَّةُ `null` قَبلَ وبَعد.
            "studio",

            // ─── وَثائِقُ الزَحفِ عَلى الجَذر ─────────────────────────
            "robots.txt", "sitemap.xml",

            // ─── سَطحُ الـAPI — المُستَأجِرُ مِن الاعتِمادِ لا المَسار ─
            "api",

            // ─── صَفَحاتُ عَودَةِ الدَفعِ (‏ADR-006، ADR-009) ─────────
            "billing",

            // ─── صَفَحاتُ المَنَصَّةِ الخَمس — شَرطُ اعتِمادِ النِطاق ──
            "terms", "privacy", "refunds", "pricing", "contact",
        };

    /// <summary>أَهذا الاسمُ مَحجوز؟ — <b>الفَراغُ لَيسَ مَحجوزاً بَل
    /// غائِب</b>، ويَرُدُّه فاحِصُ الشَكلِ لا هذا.</summary>
    public static bool Contains(string? slug)
        => !string.IsNullOrWhiteSpace(slug) && All.Contains(slug.Trim());
}
