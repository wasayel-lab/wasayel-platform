using System.Linq.Expressions;

namespace ACommerce.Templates.Customer.Marketplace.Services.Incubator;

/// <summary>
/// سِجِلّ مُوافَقَة المُستَخدِم على شُروط الحاضِنَة (المَرحَلَة ٧).
/// يُحفَظ تَحت tenant "_studio". وُجود سِجِلّ بِنَفس <c>Version</c> الحالي
/// = المُستَخدِم وافَق. تَغيير الـ Version يُجبِر القَبول مَرَّة أُخرى.
/// </summary>
public sealed class ConsentRecord
{
    public Guid Id { get; set; }
    public Guid UserId { get; set; }
    public int Version { get; set; }
    public DateTime At { get; set; } = DateTime.UtcNow;
    public string Ip { get; set; } = "";
    public string UserAgent { get; set; } = "";
}

public static class ConsentPolicy
{
    /// <summary>إصدار الشُروط الحاليّ — بَدِّلها لِتُجبِر القَبول مَرَّة أُخرى.
    ///
    /// <para><b>‏1 → 2 في ‏2026-10-11</b> (موجَزُ الفَجَوات P2-1): البَندُ الرابِعُ كانَ
    /// يَقولُ «الدَّفع مُسَجَّل كَ نِيَّة فَقَط … (لا يَتِم تَحصيل)» بَينَما باقَةُ
    /// المَتجَرِ تُضبَطُ بِسِعرٍ وتُعَلَّقُ عِندَ عَدَمِ السَداد — فَكُلُّ مَن قَبِلَ
    /// الإصدارَ 1 يُعادُ إلَيه النَصُّ الصادِقُ قَبلَ تَحليلِه التالي.</para>
    ///
    /// <para><b>‏2 → 3 في ‏2026-10-29</b> (قَرارا المالِك د20 ود18، في رَفعٍ واحِدٍ كَي لا يُطلَبَ القَبولُ مَرَّتَين): البَندُ الثالِثُ كانَ
    /// يَقولُ «لا نُشارِكها مَع أَطراف ثالِثَة» والبَندُ الأَوَّلُ نَفسُه يَقولُ إنّ الدِراسَةَ يُولِّدُها نَموذَجُ ذَكاءٍ اصطِناعيّ — فَصارَ «لا نَبيعُ
    /// بَياناتِك، ونُشارِكُها مَعَ مُزَوِّدِ نَموذَجِ اللُغَةِ … ومَعَ الجِهاتِ المُسَمّاةِ في سِياسَةِ الخُصوصِيَّةِ فَقَط»؛ والبَندُ الرابِعُ «الباقاتُ
    /// والاشتِراك» بِصِياغَةِ المالِك: الحُدودُ والتَجَدُّد، والاتِّفاقُ عَلى الاشتِراك، ومُهلَةُ السَماحِ ثُمَّ الإخفاء، والتَعليقُ عِندَ عَدَمِ السَداد،
    /// والإحالَةُ إلى البَندَينِ ٤ و٩ مِن شُروطِ المَنَصَّة.</para>
    ///
    /// <para><b>‏3 → 4 في ‏2026-11-07</b> (الموجَة ١٣ W13-1·٨ — ADR-049 §٥): خَرَجَ التَحليلُ مِن رِحلَةِ رائِدِ الأَعمال، والبُنودُ تَقولُ «الدِراساتُ
    /// يُولِّدُها نَموذَجُ ذَكاءٍ اصطِناعيّ» و«تَبنيه عَلى التَحليل» و«نُشارِكُها مَعَ مُزَوِّدِ نَموذَجِ اللُغَةِ لِتَوليدِ الدِراسَة» و«التَحاليلُ والتَحسيناتُ
    /// تَتَجَدَّدُ» و«التَحاليلُ القَديمَةُ تَبقى صالِحَةً» — وَعدٌ وإفصاحٌ عَمّا لا يَحدُث. فَسَقَطَت جُمَلُ التَحليلِ والنَموذَجِ كُلُّها، وبَقِيَت جُمَلُ
    /// الاشتِراكِ والسَماحِ والتَعليقِ في البَندِ الرابِعِ بِحَرفِها، والبَندُ الأَوَّلُ يَقولُ ما تَقولُه شُروطُ المَنَصَّةِ (البَندانِ ٢ و٧) عَن المُحتَوى.
    /// ويُسأَلُ كُلُّ مُستَخدِمٍ قائِمٍ القَبولَ قَبلَ إنشاءِ مَتجَرِه التالي. والصِياغَةُ لِلوَكيلِ حَتّى يَكتُبَ المالِكُ صِياغَتَه («ب» في سِجِلِّه).</para></summary>
    public const int CurrentVersion = 4;

    /// <summary>
    /// <para><b>شَرطُ «وافَقَ عَلى هذا الإصدار»</b> — مُسنَدٌ واحِدٌ يَقرَؤُه بابُ
    /// صَفحَةِ الشُروطِ (<c>StudioQueries.HasConsentedAsync</c>) ونُقطَةُ استِئنافِ
    /// المُطالَبَةِ قَبلَ أَوَّلِ تَحليل (<c>ResumeStudioPromptAsync</c>)، فَلا نُسخَتانِ
    /// تَنجَرِفان (القاعِدَة ٨؛ كانَتا نُسخَتَينِ مُتَطابِقَتَينِ في مَوضِعَين حَتّى
    /// ‏2026-10-11). والمُساواةُ لا <c>&gt;=</c> مَقصودَة: سِجِلُّ إصدارٍ أَقدَمَ لا
    /// يَكفي، وهذا بِعَينِه ما يُجبِرُ القَبولَ مَرَّةً أُخرى حينَ يُرفَعُ
    /// <see cref="CurrentVersion"/>.</para>
    /// <para>تَعبيرٌ لا دالَّة: يُمَرَّرُ إلى <c>Where</c> فَيُتَرجِمُه Marten إلى SQL،
    /// ويُجَمَّعُ في الاختِبارِ فَيُقاسُ بِلا قاعِدَةِ بَيانات.</para>
    /// <para><b>شَرطُ الاستِخراجِ</b> (القاعِدَة ١ — مُستَهلِكانِ لا ثَلاثَة، ‏2026-10-13): استُخرِجَ لِأَنّ قارِئَي
    /// مُسنَدٍ واحِدٍ يَجِبُ أَن يَتَحَرَّكا مَعاً حينَ يُرفَعُ الإصدار، ولا ثالِثَ مُتَوَقَّع — فَإن بَقِيَ قارِئٌ واحِدٌ
    /// أُعيدَ المُسنَدُ مُضَمَّناً فيه.</para>
    /// <para>‏(‏2026-11-07، الموجَة ١٣ W13-1·٨ — يُلحَقُ ولا يُعادُ حَرفٌ فَوقَه) <b>بَقِيَ قارِئٌ واحِد</b>: خَرَجَت نُقطَةُ الاستِئنافِ في ·٥، وبابُ
    /// الإنشاءِ وصَفحَتاه يَسأَلونَ <c>StudioQueries.HasConsentedAsync</c> — فَالشَرطُ المَكتوبُ أَعلاهُ تَحَقَّق. ولَم يُضَمَّن: هو ما يُقاسُ بِلا قاعِدَةٍ
    /// في <c>StudioConsentPolicyTests</c> عِندَ كُلِّ رَفعٍ لِلإصدار (وهذا الرَفعُ مِنها)، والتَضمينُ يَنقُلُ ذلكَ القِياسَ إلى Postgres. قَرارٌ مَرئِيٌّ
    /// («أ» في سِجِلِّ المالِك) لا نِسيان.</para>
    /// </summary>
    public static Expression<Func<ConsentRecord, bool>> AcceptedBy(Guid userId, int version)
        => c => c.UserId == userId && c.Version == version;
}
