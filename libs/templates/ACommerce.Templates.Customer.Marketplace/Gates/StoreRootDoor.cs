using ACommerce.Kit.Roles;

namespace ACommerce.Templates.Customer.Marketplace.Gates;

/// <summary>
/// <para><b>جَذرُ المَتجَرِ لِلزائِر: البِضاعَةُ أَوَّلاً، وبِطاقاتُ الأَدوارِ تَحتَها</b> (‏2026-10-29، قَرارُ المالِك د34 الخِيارُ ١؛ ‏ADR-048 يُعَدِّلُ ‏ADR-035).
/// دالّتانِ نَقِيَّتان — بِلا قاعِدَةٍ ولا HTTP — تَأخُذانِ ما قَرَأَتهُ الصَفحَة.</para>
///
/// <para><b>العِلَّةُ المَقيسَة</b>: زائِرُ <c>/{slug}</c> لِمَتجَرٍ ذي أَدوارٍ — وكُلُّ مَتجَرٍ مِن الاستوديو ذو أَدوار (‏ADR-027) — كانَ يَرى بَوّابَةَ الأَدوارِ
/// وَحدَها بِلا بِضاعَةٍ ولا شَريط (‏<c>StoreRootVisitorCharacterizationTests</c>، اللَقطَةُ الحَيَّةُ <c>ashare-portal</c>)، والمَتاجِرُ الشائِعَةُ تَعرِضُ
/// البِضاعَةَ قَبلَ أَن تَطلُبَ التَسجيل.</para>
///
/// <para><b>«دَورُ المُشتَري» مَقيسٌ لا مُسَمّى</b>: دَورٌ مِن أَدوارِ المَتجَرِ تَرسُمُه البَوّابَةُ بِطاقَةً (كُلُّ ما سِوى <c>tenant_admin</c> — شَرطُ
/// <c>RoleLanding</c> نَفسُه)، <b>تَركيبُ رَئيسِيَّتِه <see cref="RoleComponents.DefaultHome"/></b> — الفَرعُ الافتِراضِيُّ في <c>TenantHome</c> الَّذي
/// يَراه زائِرُ مَتجَرٍ بِلا أَدوار، وهُوَ «رَئيسِيَّةُ المُشتَري» بِعَينِها — <b>ويَحمِلُ <c>listing.browse</c></b>. في الكاتالوجِ اليَومَ <c>customer</c>
/// وَحدَه (مُثَبَّت)؛ ودَورٌ مُؤَلَّفٌ بِالتَركيبِ الافتِراضِيِّ يَتَصَفَّحُ يُعَدُّ مِثلَه بِلا سَطرٍ هُنا، ودَورٌ مُؤَلَّفٌ بِالتَركيبِ نَفسِه لا يَتَصَفَّحُ لا يُعَدّ.
/// فَمَتجَرٌ أَدوارُه <c>rider</c> و<c>driver</c> (‏<c>injez</c>) يَبقى عَلى البَوّابَة — نَصُّ القَرار.</para>
///
/// <para><b>والنِطاقُ نَصُّ السُؤال — «صَفحَةُ المَتجَر»</b>: الزائِرُ غَيرُ المُسَجَّلِ عَلى <c>/{slug}</c>. ومَن يَفتَحُ تَطبيقَ دَورٍ مُباشَرَةً (<c>/{slug}/r/{role}</c>)
/// اختارَ الدَورَ في الرابِطِ فَيَبقى عَلى بَوّابَتِه، والمُسَجَّلُ بِلا دَورٍ فَعّالٍ يَبقى عَلَيها كَما كان — كِلاهُما مُثَبَّتٌ بِحَرفِه.
/// <b>ولا إعدادَ لِلمَتجَرِ الآن</b>: الخِيارُ يُبنى يَومَ يَطلُبُه أَوَّلُ صاحِبِ مَتجَر (نَصُّ القَرار، القاعِدَة ١).</para>
///
/// <para><b>‏2026-10-30 — والنِطاقُ يَتَّسِعُ لِمَن يَرى اليَومَ البَوّابَةَ وهو مُشتَرٍ في الأَثَر</b> (تَدقيقُ الموجَة ١١ CO5، مُرَحَّلٌ [S6·٣]؛ قَرارٌ تَحتَ P1
/// بِاتِّساقِ د34 «يَرى الزائِرُ البِضاعَةَ أَوَّلاً»؛ تَوصيفُه <c>d453ac4</c>؛ يُلحَقُ ولا يُعادُ حَرفٌ فَوقَ ما سَبَق): الفِقرَةُ أَعلاه أَبقَت اثنَينِ عَلى البَوّابَة —
/// (١) <b>تَطبيقُ دَورِ المُشتَري مَفتوحاً بِلا جَلسَة</b> (<c>/{slug}/r/customer</c>، وهو <c>start_url</c> تَطبيقِ المُشتَري المُثَبَّت)، و(٢) <b>المُسَجَّلُ بِلا دَورٍ
/// فَعّالٍ في هذا المَتجَر</b> — وكِلاهُما يَطلُبُ ما يَطلُبُه زائِرُ الجَذر: البِضاعَة. فَصارا يَرَيانِ رَئيسِيَّةَ المُشتَري والبِطاقاتُ تَحتَها. <b>وما بَقِيَ
/// عَلى حالِه</b>: تَطبيقُ دَورٍ غَيرِ المُشتَري (<c>r/host</c>، <c>r/vendor</c>) لِلزائِرِ عَلى بَوّابَتِه، والمُسَجَّلُ بِدَورٍ فَعّالٍ يَرى رَئيسِيَّةَ دَورِه.</para>
///
/// <para><b>والمُستَهلِكان</b> (القاعِدَة ٨ — قَرارٌ واحِدٌ في مَوضِعٍ واحِد): <c>TenantHome</c> (أَيُّ فَرعٍ يُرسَم، وقِسمُ البِطاقاتِ تَحتَ البِضاعَة)
/// و<c>MainLayout</c> (الشَريطُ مَخفِيٌّ عَلى البَوّابَةِ وَحدَها — «لا nav قَبل أَن يَختار المُستَخدِم دَوراً» يَصدُقُ عَلى صَفحَةِ الاختِيارِ لا عَلى رَئيسِيَّةِ المُشتَري).
/// <b>وشَرطُ الاستِخراجِ (القاعِدَة ١)</b>: مُستَهلِكانِ في وَقتِ التَشغيلِ يَومَ وُلِدَت، لِأَنّ القَرارَ نَفسَه يَحكُمُ الصَفحَةَ وشِلَّها — وتَفَرُّقُه
/// بَينَهُما يَرسُمُ رَئيسِيَّةً بِلا شَريطٍ أَو بَوّابَةً بِشَريط. ومُستَهلِكٌ ثالِثٌ لا يُضافُ إلّا بِصَفٍّ يُسَمّيه في <c>StoreRootDoorTests</c>.</para>
/// </summary>
public static class StoreRootDoor
{
    /// <summary>دَورُ الإدارَةِ الَّذي لا تَرسُمُه البَوّابَةُ بِطاقَة — شَرطُ <c>RoleLanding</c> بِحَرفِه.</summary>
    public const string AdminRole = "tenant_admin";

    /// <summary>صَلاحِيَّةُ التَصَفُّح — مِن <see cref="PermissionCatalog.All"/>.</summary>
    public const string BrowsePermission = "listing.browse";

    /// <summary>أَهذا دَورُ مُشتَرٍ؟ — بِطاقَةٌ في البَوّابَة، رَئيسِيَّتُها رَئيسِيَّةُ المُشتَري، وتَتَصَفَّح.</summary>
    public static bool IsBuyerRole(Role role, TenantRoleSet roleSet)
        => role.CatalogSlug != AdminRole
           && role.Permissions.Contains(BrowsePermission)
           && roleSet.ResolveComposition(role.CatalogSlug).Home == RoleComponents.DefaultHome;

    /// <summary>
    /// <para><b>أَيَرى هذا الزائِرُ البِضاعَةَ أَوَّلاً؟</b> — في مَتجَرٍ ذي أَدوارٍ فيه دَورُ مُشتَرٍ: <b>غَيرُ المُسَجَّلِ</b> عَلى الجَذرِ بِلا دَورٍ في المَسار
    /// <b>أَو عَلى تَطبيقِ دَورِ مُشتَرٍ</b> (<paramref name="urlRole"/>)، و<b>المُسَجَّلُ</b> الَّذي لا يُسَمّي دَورُه الفَعّالُ (<paramref name="memberRole"/> — دَورُ المَسارِ
    /// وإلّا المُخَزَّن، قِراءَةُ المُستَهلِكَينِ نَفسُها) دَوراً مِن أَدوارِ هذا المَتجَر. <c>false</c> لِكُلِّ ما سِوى ذلك، فَيَبقى ما كانَ بِحَرفِه: البَوّابَةُ
    /// لِمَتجَرٍ ذي أَدوارٍ بِلا دَورِ مُشتَر ولِتَطبيقِ دَورٍ غَيرِ المُشتَري، ورَئيسِيَّةُ الدَورِ لِمَن لَه دَورٌ فَعّال، ورَئيسِيَّةُ المُشتَري لِمَتجَرٍ بِلا أَدوار.</para>
    /// </summary>
    public static bool GoodsFirst(IReadOnlyCollection<Role> tenantRoles, TenantRoleSet roleSet, bool authenticated, string? urlRole, string? memberRole)
        => tenantRoles.Count > 0
           && tenantRoles.Any(r => IsBuyerRole(r, roleSet))
           && (authenticated
               ? string.IsNullOrEmpty(memberRole) || !tenantRoles.Any(r => r.Slug == memberRole)
               : string.IsNullOrEmpty(urlRole) || tenantRoles.Any(r => r.Slug == urlRole && IsBuyerRole(r, roleSet)));
}
