#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════
#  بَوّابَة القَبول — «الـ HTML خارِج كُتلَة الرُموز مُطابِق بايتاً بِبايت»
# ───────────────────────────────────────────────────────────────────────
#  يَلتَقِط الصَفَحات المَرجِعِيَّة الآن، يَنزَع مِنها **كُتلَة واحِدَة**
#  هي <style id="wsl-theme">…</style> (وهي الإضافَة الوَحيدَة المَأذون
#  بِها في هذه المَوجَة)، ثُمَّ يُقارِن الباقي بِلَقطَة الأَساس
#  المُلتَقَطَة قَبل أَيّ تَحويل.
#
#  أَيّ فَرق خارِج تِلكَ الكُتلَة = فَشَل. لا «يَبدو مُطابِقاً»، ولا
#  حُكم بِالعَين: `cmp` هو الحَكَم.
#
#  الاستِعمال:
#     scripts/compare-appearance.sh [BASELINE_DIR] [BASE_URL]
# ═══════════════════════════════════════════════════════════════════════
set -euo pipefail

BASELINE="${1:-tests/characterization/appearance/baseline}"
BASE_URL="${2:-http://localhost:5050}"
AFTER="$(mktemp -d)"
STRIPPED="$(mktemp -d)"

trap 'rm -rf "$AFTER" "$STRIPPED"' EXIT

bash "$(dirname "$0")/capture-appearance.sh" "$AFTER" "$BASE_URL" > /dev/null

fail=0
compared=0
for f in "$BASELINE"/*.html; do
  name="$(basename "$f")"
  compared=$((compared + 1))
  # نَزع كُتلَة الرُموز وَحدَها. الحُدود صَريحَة (المُعَرِّف wsl-theme)
  # لا تَخمينِيَّة، ويُنزَع مَعَها **سَطرُها كامِلاً**: المَسافات
  # البادِئَة، وسَطرُ الفَراغ الَّذي يَتلوها — لِأَنّ البايتات
  # المُضافَة فِعلاً في <head> هي هذان السَطران، لا الوَسم وَحدَه.
  #
  # ونَزع سَطر الفَراغ لَيسَ تَساهُلاً: لَو تَغَيَّرَ شَكل الإدراج يَوماً
  # فَلَم يَعُد يُنتِج ذلك الفَراغ، **فَشِلَت** المُقارَنَة بِصَوت عالٍ
  # ولَم تَمُرّ صامِتَةً. النَّمَط يَنكَسِر ظاهِراً لا يَتَساهَل خَفِيّاً.
  perl -0pe 's{[ \t]*<style id="wsl-theme">.*?</style>\r?\n\r?\n}{}s' \
      "$AFTER/$name" > "$STRIPPED/$name"

  if cmp -s "$f" "$STRIPPED/$name"; then
    echo "✓ $name — مُطابِق بايتاً بِبايت خارِج كُتلَة الرُموز"
  else
    echo "✗ $name — فَرق خارِج كُتلَة الرُموز:"
    # `|| true` لَيسَ تَزييناً: تَحتَ `set -eo pipefail` يُغلِق `head`
    # الأُنبوب فَيَموت `diff` بِـSIGPIPE فَيَفشَل الأَنبوب فَيَخرُج
    # السكربت **عِندَ أَوَّل صَفحَة حَمراء** — فَحالَة الخَمس الباقِيَة
    # لا تُطبَع أَبَداً. (قيسَ 2026-08-11: صَفحَة واحِدَة أَخفَت خَمساً.)
    # نَفس عَطَب `head -3` المُوَثَّق في VERIFICATION-LAYERS.md، ونَفس
    # المَبدَأ في `verify-static.sh`: طَبَقَةٌ مَكسورَة لا تُخفي حالَة
    # البَقِيَّة.
    { diff <(fold -w120 "$f") <(fold -w120 "$STRIPPED/$name") | head -20; } || true
    fail=1
  fi
done

# حارِس العَمى (‏القاعِدَة ١٠): «صِفر فَرق» مِن أَداةٍ قارَنَت صِفر
# صَفَحات لا يُمَيَّز عَن «صِفر فَرق» مِن أَداةٍ قارَنَت كُلَّها. ودَليل
# مِن هذا المُستَودَع: وَكيلٌ قارَنَ مُستَودَعاً بِنَفسِه فَأَعطى «صِفر
# فُروق». فَالعَدَد يُطبَع، والصِفر يُحمِر.
echo "الصَفَحات المُقارَنَة: $compared"
if [ "$compared" -eq 0 ]; then
  echo "✗ فَحصٌ أَعمى: لا لَقطَة أَساس في «$BASELINE» — لا شَيءَ قُورِن." >&2
  exit 1
fi

if [ "$fail" -eq 0 ]; then
  echo "بَوّابَة القَبول: خَضراء — لا بايت تَغَيَّرَ خارِج كُتلَة الرُموز."
else
  echo "بَوّابَة القَبول: حَمراء." >&2
fi
exit "$fail"
