#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════
#  بُرهانُ «الفَرقُ تَرميزيٌّ بَحت» — الطَرَفُ الثاني لِبَوّابَة القَبول
# ───────────────────────────────────────────────────────────────────────
#  الاستِعمال:
#     scripts/prove-encoding-only.sh <OLD_DIR> <NEW_DIR>
#
#  ── المُشكِلَة الَّتي وُجِدَ لَها ──────────────────────────────────────
#  ‏`compare-appearance.sh` تُقارِن **بايتاً بِبايت**، وهذا عَينُ ما
#  يُرادُ مِنها: التَشكيلُ يَسقُط صامِتاً وإلّا. لكِنَّها لِذلك بِالضَبط
#  تَحمَرُّ أَمامَ تَبَدُّلٍ **لا يَراهُ المُستَخدِم**: نَصٌّ ساكِنٌ
#  يُرَحَّل إلى تَعبير، فَيَنقَلِبُ عُنصُرُه ديناميكِيّاً، فَيَتَبَدَّل
#  مِحوَران مَعاً (‏docs/I18N.md §٨-د-ب):
#
#     ساكِن:      <input class="ac-chip-entry" placeholder="أَضِف حَيّاً…">
#     ديناميكيّ:  <input class="ac-input" placeholder="&#x627;&#x636;…" />
#
#  فَالخِياران أَمامَ خَمسَةٍ وسِتّينَ مَوضِعاً كانا: أَن تَبقى حَرفِيَّةً
#  إلى الأَبَد، أَو أَن يُقبَل تَبَدُّلُ البايتات **بِلا بُرهان**.
#  وهذا المِلَفّ ثالِثٌ: يُقبَل التَبَدُّل، **ويُبرهَن أَنَّه هو هو**.
#
#  ── ما يُطَبِّعُه، ولا شَيءَ سِواه ────────────────────────────────────
#  ١. **مَراجِعُ المَحارِف** — الرَقَمِيَّة (`&#x627;` و`&#1575;`)
#     والمُسَمّاةُ الخَمس (`&amp; &lt; &gt; &quot; &apos;`) تُفَكّ إلى
#     مَحارِفِها. وهذا هو مِحوَرُ التَرميز.
#  ٢. **شَكلُ الوَسم** — `<x … />` ← `<x …>`. وهذا مِحوَرُ الشَكل.
#
#  وما لا يُطَبَّع، عَمداً، لِأَنّ تَطبيعَه يُخفي عَطَباً حَقيقِيّاً:
#  **الفَراغ**. الفَخُّ الأَوَّل (عُقدَةُ النَصّ الحافَّة) يَظهَر فَراغاً
#  ساقِطاً؛ فَلَو طُبِّعَ لَمَرَّ سُقوطُه صامِتاً — وهو تَبَدُّلٌ
#  **مَرئيّ** في الصَفحَة.
#
#  ── والأَداةُ تُقاس قَبلَ أَن يُوثَقَ بِها (‏CLAUDE.md القاعِدَة ١٠) ──
#  تَطبع عَدَدَ ما قارَنَته وتَفشَل إن كانَ صِفراً؛ و`--self-test` يَحقِن
#  عَيباً حَقيقِيّاً (شَكلَةٌ تَسقُط) في نُسخَةٍ مُؤَقَّتَة ويَشتَرِط أَن
#  تَحمَرّ. «صِفرُ فَرق» مِن مُطَبِّعٍ يَبتَلِع كُلَّ شَيء لا يُميَّز عَن
#  «صِفرُ فَرق» مِن مُطَبِّعٍ يَرى.
# ═══════════════════════════════════════════════════════════════════════
set -eo pipefail
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

SELF_TEST=0
if [ "${1:-}" = "--self-test" ]; then SELF_TEST=1; shift; fi

OLD_DIR="${1:?الاستِعمال: prove-encoding-only.sh [--self-test] <OLD_DIR> <NEW_DIR>}"
NEW_DIR="${2:?الاستِعمال: prove-encoding-only.sh [--self-test] <OLD_DIR> <NEW_DIR>}"

if ! command -v perl > /dev/null 2>&1; then
    echo "  ✗ BLIND CHECK: perl غَير مَوجود — المُطَبِّع لا يَعمَل." >&2
    exit 1
fi

TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT

cat > "$TMP/normalize.pl" <<'PERL'
use strict; use warnings;
binmode(STDIN, ':raw'); binmode(STDOUT, ':raw');
local $/;
my $s = <STDIN>;
$s = '' unless defined $s;
utf8::decode($s);

# ١. شَكلُ الوَسم: `<x … />` ← `<x …>`  — قَبلَ فَكِّ المَراجِع، فَقيمَةٌ
#    مَفكوكَةٌ قَد تَحمِل `/>` نَصّاً.
$s =~ s{\s*/>}{>}g;

# ٢. مَراجِعُ المَحارِف — الرَقَمِيَّة ثُمَّ المُسَمّاةُ الخَمس.
$s =~ s/&#x([0-9A-Fa-f]+);/chr(hex($1))/ge;
$s =~ s/&#([0-9]+);/chr($1)/ge;
$s =~ s/&lt;/</g;
$s =~ s/&gt;/>/g;
$s =~ s/&quot;/"/g;
$s =~ s/&apos;/'/g;
$s =~ s/&amp;/&/g;      # أَخيراً: وإلّا فُكَّ `&amp;lt;` مَرَّتَين

# ٣. `CR` **بَعدَ الفَكّ** — تَناظُرٌ مَع خَطّ الالتِقاط لا تَساهُل.
#    ‏`capture-appearance.sh` يَمُرّ بِـ`sed` فَيُسقِط `CR` الخام مِن
#    الطَرَفَين (مَقيس: صِفرُ `CR` في كُلّ لَقطات الأَساس). وخاصِّيَّةٌ
#    مُتَعَدِّدَةُ الأَسطُر تَطبَع نِهاياتِ سُطورِها في الصَفحَة: ساكِنَةً
#    تَخرُج `CR` خاماً فَيُسقِطُها الخَطّ، وديناميكِيَّةً تَخرُج
#    `&#xD;` فَيَنجو مِن الخَطّ ويُفَكُّ هُنا. فَتَركُه يَجعَل
#    المُقارَنَة غَيرَ مُتَناظِرَة ويَتَّهِم الشيفرَة بِعَطَبِ الأَداة.
#    المَقيس: ثَلاثُ صَفَحات، ‏2 `CR` في كُلٍّ — `studio-consent`
#    (`style` على سَطرَين) و`user/member-notifications` (`onclick`
#    على سَطرَين)، ولا حَرفَ سِواها.
$s =~ s/\r//g;

utf8::encode($s);
print $s;
PERL

# ── حَقنُ العَيب لِقياسِ الأَداة ──────────────────────────────────────
# شَكلَةٌ واحِدَة (فَتحَة U+064E) تَسقُط مِن أَوَّل مَوضِعٍ في كُلّ مِلَفٍّ
# جَديد. تَبَدُّلٌ **حَقيقيّ** لا تَراهُ العَين، وهو ما يَجِب أَن يَراه
# المُطَبِّع.
inject() {
    perl -e '
        binmode(STDIN, ":raw"); binmode(STDOUT, ":raw");
        local $/; my $s = <STDIN>; utf8::decode($s);
        $s =~ s/\x{064E}// ;
        utf8::encode($s); print $s;'
}

TOTAL=0; SAME=0; DIFF=0
: > "$TMP/report.txt"

for old in "$OLD_DIR"/*.html; do
    [ -e "$old" ] || continue
    name=$(basename "$old")
    new="$NEW_DIR/$name"
    if [ ! -f "$new" ]; then
        echo "  ✗ $name — لا نَظير في $NEW_DIR" >> "$TMP/report.txt"
        DIFF=$((DIFF + 1)); TOTAL=$((TOTAL + 1))
        continue
    fi

    TOTAL=$((TOTAL + 1))
    perl "$TMP/normalize.pl" < "$old" > "$TMP/a"
    if [ "$SELF_TEST" -eq 1 ]; then
        inject < "$new" | perl "$TMP/normalize.pl" > "$TMP/b"
    else
        perl "$TMP/normalize.pl" < "$new" > "$TMP/b"
    fi

    if cmp -s "$TMP/a" "$TMP/b"; then
        SAME=$((SAME + 1))
    else
        DIFF=$((DIFF + 1))
        {
            echo "  ✗ $name — فَرقٌ **غَير** تَرميزيّ:"
            # ‏`|| true`: مَع `pipefail` يُرجِع `diff` واحِداً عِندَ
            # الاختِلاف — وهو الحالَةُ الَّتي نَحنُ فيها أَصلاً.
            { diff "$TMP/a" "$TMP/b" || true; } | head -8 | sed 's/^/      /'
        } >> "$TMP/report.txt"
    fi
done

echo "═══════════════════════════════════════════════"
echo "   بُرهان: الفَرقُ تَرميزيٌّ بَحت"
echo "═══════════════════════════════════════════════"
echo "  القَديم: $OLD_DIR"
echo "  الجَديد: $NEW_DIR"
if [ "$SELF_TEST" -eq 1 ]; then echo "  ⚙ وَضعُ قِياسِ الأَداة: شَكلَةٌ مَحقونَةٌ في كُلّ مِلَفّ جَديد."; fi
echo ""

# حارِسُ العَمى: مُقارِنٌ قارَنَ صِفراً لا يُميَّز عَن مُقارِنٍ لا يَعمَل.
if [ "$TOTAL" -eq 0 ]; then
    echo "  ✗ BLIND CHECK: صِفرُ صَفحَة قوبِلَت — المَسارُ خاطِئ أَو الدَليلُ فارِغ." >&2
    exit 1
fi

cat "$TMP/report.txt"
echo "  الصَفَحات المُقارَنَة: $TOTAL   مُتَطابِقَة بَعدَ التَطبيع: $SAME   مُختَلِفَة: $DIFF"
echo ""

if [ "$SELF_TEST" -eq 1 ]; then
    if [ "$DIFF" -eq "$TOTAL" ]; then
        echo "✅ الأَداةُ تَرى: العَيبُ المَحقون أَحمَرَ $DIFF مِن $TOTAL."
        exit 0
    fi
    echo "✗ الأَداةُ عَمياء: عَيبٌ حَقيقيٌّ مَرَّ في $SAME صَفحَة." >&2
    exit 1
fi

if [ "$DIFF" -eq 0 ]; then
    echo "✅ خَضراء — كُلُّ فَرقٍ بَينَ الطَرَفَين تَرميزٌ أَو شَكلُ وَسم، ولا حَرفَ تَبَدَّل."
    exit 0
fi

echo "✗ حَمراء — $DIFF صَفحَة تَحمِل فَرقاً لا يُفَسِّرُه التَرميز. أَرجِع المَوضِعَ وَحدَه."
exit 1
