# أَعطَيا 28. فَالمَصدَرُ الآنَ جَدوَلُ المَقابِسِ مِن نِظامِ التَشغيل.
#
# **وثالِثٌ لِحاوِيَةٍ بِلا ss ولا netstat** (‏2026-10-12، P3-2): جَدوَلُ المَقابِسِ نَفسُه في `/proc/net/tcp` و`tcp6` — وهُوَ
# ما يَقرَؤُه `ss`. العَمودُ الثاني «عُنوان:مَنفَذ» والمَنفَذُ سِتَّةَ عَشَرِيّ، والرابِعُ الحالُ و`0A` = LISTEN. كانَت البَوّابَةُ
# تَخرُجُ هُنا بِـ3 في كُلِّ حاوِيَةٍ بِلا الأَداتَين — ومِنها الَّتي كُتِبَ فيها هذا — فَلا تَبلُغُ الإقلاعَ أَصلاً.
#
# **ومِلَفّاً مِلَفّاً لا بِـ`cat` واحِد** — مَقيسٌ لا احتِياط: `tcp6` غائِبٌ في الحاوِيَةِ الَّتي كُتِبَ فيها هذا، فَيَرجِعُ `cat`
# بِـ1، ومَعَ `pipefail` يَصيرُ الأُنبوبُ كُلُّه 1 وإن وَجَدَ `awk` المَنفَذ — فَكُلُّ مَنفَذٍ «حُرّ». وكَشَفَه الفَحصُ الذاتِيُّ
# بَعدَ الإقلاعِ (أَدناه) في أَوَّلِ تَشغيل: «لا تَرى مَنفَذَ التَطبيقِ وهُوَ يُجيب». (القاعِدَة ١٠: الأَداةُ تُقاسُ قَبلَ أَن يُوثَقَ بِها.)
port_in_use_proc() {
    local hex f
    hex="$(printf '%04X' "$1")"
    for f in /proc/net/tcp /proc/net/tcp6; do
        [ -r "$f" ] || continue
        awk -v h="$hex" '$4 == "0A" { n = split($2, a, ":"); if (toupper(a[n]) == h) found = 1 }
                         END { exit found ? 0 : 1 }' "$f" && return 0
    done
    return 1
}
port_in_use() {
    local p="$1"
    if command -v ss >/dev/null 2>&1; then
        ss -ltn 2>/dev/null | grep -qE "[:.]${p}[[:space:]]"
    elif command -v netstat >/dev/null 2>&1; then
        # ‏netstat يَعمَل على وِندوز (‏LISTENING) وعلى لينكس (‏LISTEN).
        netstat -an 2>/dev/null | grep -iE "LISTEN" | grep -qE "[:.]${p}[[:space:]]"
    else
        port_in_use_proc "$p"
    fi
}
