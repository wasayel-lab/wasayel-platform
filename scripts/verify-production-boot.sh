if [ "$ROUTE_FAILED" -ne 0 ]; then
    # ‏ومَسارٌ رَدَّ ‏500 لِأَنّ القاعِدَةَ لا تَخدِمُ (و‑٥: `/health` ‏200 و`/` ‏500 بِـ`53000`) لَيسَ كَسراً — يَسأَلُ السِجِلَّ
    # بِالدالَّةِ نَفسِها قَبلَ الحُكم.
    verdict_line="$(boot_verdict "$APP_LOG")"
    verdict=$?
    if [ "$verdict" -eq 3 ]; then
        echo "✗ مَسارٌ رَدَّ رَمزاً غَيرَ المُتَوَقَّع — **والسَبَبُ عِندَ المُشَغِّلِ لا في الكود**."
    else
        echo "✗ **كَسرٌ في الكود** — مَسارٌ رَدَّ رَمزاً غَيرَ المُتَوَقَّع."
    fi
    echo ""
    echo "─── سِجِلُّ التَطبيقِ (آخِرُ 120 سَطراً) — الرَمزُ وَحدَه لا يُشَخِّص ───"
    tail -n 120 "$APP_LOG"
    echo "─── نِهايَةُ السِجِلّ ───"
    [ -n "$verdict_line" ] && echo "$verdict_line"
    exit "$verdict"
fi

