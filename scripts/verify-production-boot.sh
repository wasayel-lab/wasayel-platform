# ═══ تَشخيصُ السُقوطِ مِن سِجِلِّ التَطبيق — تَهيئَةٌ عِندَ المُشَغِّلِ (3) أَم كَسرٌ في الكود (1) ═══
#
# **دالَّةٌ واحِدَةٌ يَقرَؤُها فَرعُ مَوتِ الإقلاعِ وفَرعُ المَساراتِ مَعاً** (‏2026-10-12، P3-2). كانَ التَمييزُ سَطرَينِ
# داخِلَ فَرعِ المَوتِ وَحدَه، وكُلُّ ما سِواهُما 1 — فَنَفادُ حِصَّةِ Neon (‏`53000`، و‑٥ في DECISIONS-PENDING) قُرِئَ «كَسراً في
# الكود» وبُحِثَ عَنه في المَكانِ الخَطَأ، وكَذلِكَ قيمَةٌ مَكتوبَةٌ خَطَأً في `Shipping__Oto__Environment` أَو
# `Payments__Paddle__Environment` يَرمي بِها `AddOtoShipping`/`AddPaddleBilling` بِاسمِ المُتَغَيِّرِ قَبلَ أَوَّلِ طَلَب.
# **ومَعجَمُها مُغلَق**: كُلُّ سَبَبٍ سَطرٌ مُسَمّىً يُطبَعُ ويُرجِعُ 3، وما لا يُعرَفُ 1 — فَالشَكُّ يُقرَأُ كَسراً لا تَهيئَة.
# **وتُشَغَّلُ وَحدَها**: `ProductionBootVerdictTests` يَقطَعُها بِعَلامَتَيها ويُشَغِّلُها بِـbash عَلى سِجِلٍّ يَصنَعُه مِن
# الاستِثناءِ الحَقيقيِّ نَفسِه (رِسالَةُ `AddPaddleBilling` و`PostgresException` بِرَمزِها) — فَلا يَنتَظِرُ التَصنيفُ حادِثَةً لِيُقاس.
# ─── بِدايَةُ boot_verdict ───
boot_verdict() {
    local log="$1" hit
    if grep -q "Postgres connection string missing" "$log"; then
        echo "التَشخيص: **تَهيئَةٌ ناقِصَة** لا كَسرٌ — ConnectionStrings__Postgres."
        return 3
    fi
    # والتَمييزُ الثاني (‏2026-10-11): حارِسُ سِرِّ التَوقيعِ يَرمي بِرَمزٍ مِن مَعجَمِ `AuthTokenSecretPolicy.All` —
    # ثَلاثَةٌ لا رابِعَ لَها، ويُقرَأُ بِحَرفِه. تَهيئَةٌ لا كَسر: سِرٌّ عَلَنِيٌّ أَو فارِغٌ أَو قَصيرٌ بَلَغَ عَمَلِيَّةَ Production.
    hit="$(grep -oE 'auth_secret_(missing|default|short)' "$log" | head -n 1 || true)"
    if [ -n "$hit" ]; then
        echo "التَشخيص: **تَهيئَةٌ ناقِصَة** لا كَسرٌ — ACOMMERCE_AUTH_SECRET (رَمزُ الخَرق: $hit)."
        return 3
    fi
    # والثالِث (‏2026-10-12): بيئَةُ مُزَوِّدٍ خارِجَ مَعجَمِها — الرِسالَةُ تَبدَأُ بِاسمِ المُتَغَيِّرِ ثُمَّ «قيمَتُه «…»».
    hit="$(grep -oE '(Shipping__Oto__Environment|Payments__Paddle__Environment) قيمَتُه «' "$log" | head -n 1 || true)"
    if [ -n "$hit" ]; then
        echo "التَشخيص: **تَهيئَةٌ ناقِصَة** لا كَسرٌ — ${hit%% *} قيمَتُه خارِجَ مَعجَمِه (اضبِطها أَو احذِفها)."
        return 3
    fi
    # والرابِع: القاعِدَةُ الَّتي سَمّاها المُشَغِّلُ لا تَخدِم — رَمزُ SqlState في `PostgresException` (سَطرُ «Unhandled
    # exception. Npgsql.PostgresException (0x80004005): 53300: …» وسَطرُ «SqlState: 53300» — مَقيسانِ مِن سِجِلٍّ حَقيقِيّ)
    # مِن مَعجَمٍ مُغلَق: صِنفُ 53 «مَوارِدُ غَيرُ كافِيَة» (‏53000 حِصَّةُ Neon في و‑٥، و53300 حَدُّ الاتِّصالات)، وصِنفُ 28
    # «اعتِمادٌ مَرفوض»، و3D000 «قاعِدَةٌ غَيرُ مَوجودَة»، وصِنفُ 08 و57P03 «لا يَقبَلُ الاتِّصال». كُلُّها مِن السِلسِلَةِ أَو
    # الخادِم، والكودُ لَم يُسأَل. وما سِواها (‏42P01 جَدوَلٌ غائِب، 23505 تَفَرُّد…) كَسرٌ — 1.
    hit="$(grep -oE '(SqlState: |PostgresException[^:]*: )[0-9A-Z]{5}' "$log" | grep -oE '[0-9A-Z]{5}$' | head -n 1 || true)"
    case "$hit" in
        53*)       why="مَوارِدُ الخادِمِ نَفِدَت: حِصَّةُ Neon أَو حَدُّ الاتِّصالات" ;;
        28*)       why="اعتِمادُ الاتِّصالِ مَرفوض: المُستَخدِمُ أَو كَلِمَةُ المُرورِ في السِلسِلَة" ;;
        3D000)     why="القاعِدَةُ المُسَمّاةُ في السِلسِلَةِ غَيرُ مَوجودَة" ;;
        08*|57P03) why="الخادِمُ لا يَقبَلُ الاتِّصالَ الآن" ;;
        *)         why="" ;;
    esac
    if [ -n "$why" ]; then
        echo "التَشخيص: **القاعِدَةُ لا تَخدِم** لا كَسرٌ — Postgres SqlState $hit ($why)."
        return 3
    fi
    # ‏ومَنفَذُ القاعِدَةِ لا يُجيبُ أَصلاً — لا SqlState، والرِسالَةُ رِسالَةُ Npgsql (مَقيسَة: «Failed to connect to …»).
    if grep -qE 'NpgsqlException[^:]*: Failed to connect to' "$log"; then
        echo "التَشخيص: **القاعِدَةُ لا تُبلَغ** لا كَسرٌ — Npgsql: Failed to connect (المُضيفُ أَو المَنفَذُ في السِلسِلَة)."
        return 3
    fi
    # والخامِس: المَنفَذُ قيلَ حُرّاً ثُمَّ لَم يُربَط — أَداةُ المَنفَذِ أَو سِباقٌ عِندَ المُشَغِّل، لا الكود.
    if grep -qiE 'address already in use' "$log"; then
        echo "التَشخيص: **المَنفَذُ مَشغول** لا كَسرٌ — قيلَ حُرّاً ثُمَّ لَم يُربَط (address already in use)."
        return 3
    fi
    echo "التَشخيص: **كَسرٌ في الكود** — لا سَبَبَ في السِجِلِّ مِن مَعجَمِ ما عِندَ المُشَغِّل."
    return 1
}
