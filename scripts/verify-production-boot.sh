# ═══ ولِماذا مَسارا التَخارُجِ هُنا بِالذات (‏ADR-020) ══════════════
#
# **‏١) لِأَنّ التَخارُجَ هُوَ المُنتَج** (القاعِدَة ١٧): شاشَةٌ لا
# تُنتِجُ عَيناً يَخرُجُ بِها المُستَخدِمُ لا تُشحَن، وهذِه هي العَينُ
# بِعَينِها. فَسُقوطُها لا يُعَدُّ عَطَبَ ميزَةٍ جانِبِيَّة.
#
# **‏٢) ولِأَنّ الطَرَفَينِ مُختَلِفانِ ولا يُغني أَحَدُهُما عَن الآخَر**:
# صَفحَةُ Razor (‏200) تُثبِتُ أَنّ **المَدخَلَ يُبلَغ**، ونُقطَةُ
# ‏`POST` (‏302 إلى بابِ الاستوديو) تُثبِتُ أَنّ **المُنتِجَ مُسَجَّلٌ
# ومَحروس** — وحادِثَةُ `BindAsync` كانَت تُسقِطُ الاثنَينِ بِـ503 قَبلَ
# أَيِّ مُعالِج.
#
# **‏٣) و‏302 لا 200 هُنا هي الجَوابُ الصَحيح**: طَلَبٌ بِلا جَلسَةِ
# استوديو يُرَدُّ إلى `‏/studio/auth`. فَـ200 على هذا المَسارِ **عَطَبٌ
# أَمنيّ** لا نَجاح — قاعِدَةُ عُملاءِ مَتجَرٍ كامِلَةً تَنزِلُ لِمَجهول.
# والبَوّابَةُ تُمسِكُ الحالَتَين: سُقوطَ التَسجيلِ وسُقوطَ الحارِس.

# ═══ ورَمزُ الحالَةِ وَحدَه أَعمى على `/health` — مَقيسٌ لا مَظنون ═════
#
# ‏`TenantHome.razor` (`@page "/{slug}"`) **يَبتَلِعُ `/health` ويَرُدُّ
# ‏200 بِـ`text/html`** — قيسَ على المَوقِعِ الحَيِّ يَومَ ‏2026-08-30
# قَبلَ تَنفيذِ النُقطَة: ‏200 · `text/html; charset=utf-8` · ‏30,812
# بايتاً. فَلَو اكتَفَت هذِه البَوّابَةُ بِالرَمز، لَكانَ **حَذفُ سَطرِ
# `app.MapBuildIdentity(...)` مِن `Program.cs` يَمُرُّ بِها خَضراءَ إلى
# الأَبَد** — تَقولُ «سُجِّلَ» وهي لَم تَفحَصِ التَسجيلَ قَطّ. وهذا
# بِعَينِه ما تُسَمّيه القاعِدَة ١٠ أَداةً عَمياء.
#
# **وحَدُّها مُصَرَّحٌ بِه**: تُثبِتُ أَنّ المَسارَ **سُجِّلَ ويَرُدُّ
# بَصمَةً**، ولا تُثبِتُ أَنّ البَصمَةَ **صادِقَة** — الصِدقُ يُقاسُ في
# ‏`Health_body_does_not_move_when_the_environment_moves` وفي بَوّابَةِ
# النَشرِ الحَيَّة.
#
# ═══ و`"commit"` وَحدَه أَعمى بِدَورِه — العَيبُ حُقِنَ وقيسَ ══════════
#
# اشتِراطُ **وُجودِ المِفتاح** يَخضَرُّ على `"unknown"` وعلى رَقَمٍ
# يَشتَقُّه SourceLink مِن رَأسِ git سَواءً — أَي أَنَّه يُثبِتُ
# التَسجيلَ ولا يُثبِتُ أَنّ **البَصمَةَ المُمَرَّرَةَ هي الواصِلَة**.
# فَالمَشروطُ الآنَ القيمَةُ حَرفاً: نُشِرَ بِـ`$GATE_STAMP` فَيَجِبُ
# أَن يَرُدَّها الجِسمُ بِعَينِها. وبِهذا تُقاسُ السِلسِلَةُ كامِلَةً هُنا
# لا في الإنتاج.
#
# ═══ و`/health/ready` بِالجِسمِ نَفسِه لا بِالرَمز (‏2026-10-12، P3-4) ════════
# نُقطَةُ الجاهِزِيَّةِ تَسأَلُ القاعِدَةَ بِـ`select 1`، وهُنا تُقاسُ عَلى الأُنبوبِ الكامِلِ لا عَلى مُضيفٍ
# مُصَغَّر. و‏200 وَحدَه لا يَكفي لِلعِلَّةِ نَفسِها أَعلاه: `"ready":true` هُوَ ما لا تَكتُبُه صَفحَةٌ
# تَبتَلِعُ المَسار. وقاعِدَةٌ لا تُجيبُ لا تَصِلُ هذِه الخُطوَةَ أَصلاً — البَذرُ قَبلَ الاستِماعِ يَسقُطُ أَوَّلاً.
declare -A BODY_MUST_CONTAIN=(
    ["GET|/health"]="\"commit\":\"${GATE_STAMP}\""
    ["GET|/health/ready"]='"ready":true'
)

# ═══ والرَأسُ يُقاسُ على الأُنبوبِ الكامِلِ لا على مُضيفٍ مُصَغَّر ═════
# ‏`Health_forbids_caching` يُثبِتُ الرَأسَ على مُضيفٍ يَحمِلُ النُقطَةَ
# وَحدَها. وهُنا الأُنبوبُ كامِلٌ — ‏Serilog وStaticFiles وRouting
# وAntiforgery وحَلُّ المُستَأجِرِ والثَقافَةُ وبَوّابَةُ الإصدارِ ثُمَّ
# النِقاط — و**مُصَيِّرُ Razor يَضبُطُ `Cache-Control` بِنَفسِه على
# الصَفَحات**. فَإثباتُ أَنّ رَأسَنا يَصِلُ **مِن هُنا** لا مِن هُناك.
#
# **والقيمَةُ صَغيرَةُ الأَحرُفِ عَمداً، والمُقارَنَةُ تُطَبِّعُ الرُؤوسَ
# قَبلَها** — لا بِـ`grep -i`. والسَبَبُ مَقيسٌ لا احتِياطيّ: ‏`grep -qiF`
# في GNU grep ‏3.0 على Git Bash **يَنهار بِـSIGABRT** (خَرَجَ ‏134)،
# بَينَما `-qF` و`-qi` كُلٌّ وَحدَه يَعمَل. وقَد وَقَعَ فِعلاً في أَوَّلِ
# تَشغيلٍ لِهذا الفَحص: الرَأسُ كانَ حاضِراً صَحيحاً، **والأَداةُ هي
# الَّتي انهارَت** فَاتَّهَمَت التَطبيقَ بِرَدٍّ قابِلٍ لِلتَخزين.
# (القاعِدَة ١٠: الأَداةُ تُقاسُ قَبلَ أَن يُوثَقَ بِها.)
#
# **و`HEAD` مَعَ `GET`**: مُعظَمُ أَدَواتِ المُراقَبَةِ تَبعَثُ `HEAD`
# افتِراضاً، و`MapGet` وَحدَه كانَ يُسقِطُ الطَلَبَ إلى `@page "/{slug}"`
# فَيُرَدُّ ‏200 بِـ`text/html` — **مُراقِبٌ يَطمَئِنُّ إلى صَفحَةٍ لَيسَت
# النُقطَة**. وهذا هو المَوضِعُ الوَحيدُ الَّذي يُقاسُ فيه ذلكَ على
# الأُنبوبِ الكامِل؛ المُضيفُ المُصَغَّرُ في الاختِباراتِ لا يَحمِلُ
# `/{slug}` أَصلاً فَلا يَرى الابتِلاع.
# والقيمَةُ قائِمَةٌ بِفاصِلِ `;` — كُلُّ إبرَةٍ تُعَدُّ فَحصاً مُستَقِلّاً.
declare -A HEADER_MUST_CONTAIN=(
    ["GET|/health"]='no-store'
    ["HEAD|/health"]='no-store;application/json'
    ["GET|/health/ready"]='no-store'
    ["HEAD|/health/ready"]='no-store;application/json'
)

ROUTE_FAILED=0
CHECKED=0
BODY_CHECKED=0
HEADER_CHECKED=0
for entry in "${ROUTES[@]}"; do
    IFS='|' read -r method path expected <<< "$entry"
    body_file="$WORK/body.txt"
    hdr_file="$WORK/hdr.txt"
    # ‏`-X HEAD` يُعَلِّقُ curl حَتّى المُهلَة: يُرسِلُ HEAD ثُمَّ يَنتَظِرُ
    # جِسماً يَعِدُ بِه `Content-Length` ولا يَأتي. و`--head` هو الشَكلُ
    # الصَحيح. (تَعليقٌ يَبدو عَمَلاً أَسوَأُ مِن خَطَإٍ صَريح.)
    if [ "$method" = "HEAD" ]; then
        : > "$body_file"
        actual="$(curl -s --head -o /dev/null -D "$hdr_file" -w '%{http_code}' \
            --max-time 30 "http://127.0.0.1:$PORT$path" 2>/dev/null)"
    else
        actual="$(curl -s -X "$method" -o "$body_file" -D "$hdr_file" -w '%{http_code}' \
            --max-time 30 "http://127.0.0.1:$PORT$path" 2>/dev/null)"
    fi
    CHECKED=$((CHECKED + 1))

    key="${method}|${path}"

    needle="${BODY_MUST_CONTAIN[$key]:-}"
    body_ok=1
    if [ -n "$needle" ]; then
        BODY_CHECKED=$((BODY_CHECKED + 1))
        grep -qF -- "$needle" "$body_file" 2>/dev/null || body_ok=0
    fi

    hneedle="${HEADER_MUST_CONTAIN[$key]:-}"
    hdr_ok=1
    if [ -n "$hneedle" ]; then
        tr -d '\r' < "$hdr_file" 2>/dev/null | tr 'A-Z' 'a-z' > "$WORK/hdr.norm"
        IFS=';' read -r -a hneedles <<< "$hneedle"
        for hn in "${hneedles[@]}"; do
            [ -n "$hn" ] || continue
            HEADER_CHECKED=$((HEADER_CHECKED + 1))
            grep -qF -- "$hn" "$WORK/hdr.norm" || hdr_ok=0
        done
    fi

    if [ "$actual" = "$expected" ] && [ "$body_ok" = "1" ] && [ "$hdr_ok" = "1" ]; then
        if [ -n "$needle" ]; then
            printf '  ✓ %-6s %-34s %s  (الجِسمُ يَحمِل %s · والرَأسُ %s)\n' \
                "$method" "$path" "$actual" "$needle" "${hneedle:-—}"
        else
            printf '  ✓ %-6s %-34s %s\n' "$method" "$path" "$actual"
        fi
    else
        if [ "$body_ok" != "1" ]; then
            printf '  ✗ %-6s %-34s %s (الرَمزُ صَحيحٌ والجِسمُ لا يَحمِل %s — المَسارُ مُبتَلَع)\n' \
                "$method" "$path" "$actual" "$needle"
        elif [ "$hdr_ok" != "1" ]; then
            printf '  ✗ %-6s %-34s %s (الجِسمُ صَحيحٌ والرَأسُ لا يَحمِل %s — رَدٌّ قابِلٌ لِلتَخزين)\n' \
                "$method" "$path" "$actual" "$hneedle"
            echo "      ─── الرُؤوس ───"
            sed 's/^/      /' "$hdr_file" 2>/dev/null
        else
            printf '  ✗ %-6s %-34s %s (المُتَوَقَّع %s)\n' "$method" "$path" "${actual:-<لا رَدّ>}" "$expected"
        fi
        echo "      ─── مَقطَعٌ مِن الجِسم ───"
        head -c 600 "$body_file" 2>/dev/null | sed 's/^/      /'
        echo ""
        echo "      ─────────────────────────"
        ROUTE_FAILED=1
    fi
done

# حارِسُ العَمى: أَداةٌ فَحَصَت صِفراً لا تُميَّزُ عَن أَداةٍ فَحَصَت كُلَّ شَيء.
if [ "$CHECKED" -eq 0 ]; then
    echo "✗ BLIND CHECK: صِفرُ مَسارٍ مَفحوص — البَوّابَةُ تَحرُسُ لا شَيء."
    exit 1
fi
# وعَدّادٌ ثانٍ لِلفَحصِ الثاني: جَدوَلُ الأَجسامِ الفارِغُ يَجعَلُ
