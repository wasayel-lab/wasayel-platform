if [ "$HEADER_CHECKED" -eq 0 ]; then
    echo "✗ BLIND CHECK: صِفرُ رَأسٍ مَفحوص — ورَدٌّ مُخَزَّنٌ على /health هو الكَذِبَةُ بِعَينِها."
    exit 1
