#!/usr/bin/env bash
# ═══════════════════════════════════════════════════════════════════════
#  أَرضِيَّةُ البَراهينِ الحَيَّةِ الَّتي بَلَغَت قاعِدَتَها — لا «ناجِحَة» وَحدَها
# ───────────────────────────────────────────────────────────────────────
#  الاستِعمال:  ./scripts/live-proof-floor.sh <live.trx> <floor>
#
#  ‏(‏2026-10-25، مُراجَعَةُ تَيّارِ W8-5 الجَولَة ١): الحارِسُ `The_live_step_reaches_its_database` يُثبِتُ أَنّ العَلَمَ
#  مَضبوطٌ والقاعِدَةَ تُجيب، ولا يَعُدُّ كَم بُرهاناً بَلَغَها فِعلاً — وبُرهانٌ يَرجِعُ مِن حارِسٍ فَرعِيٍّ (رَمزٌ غائِب،
#  وَثيقَةٌ لَم تُبذَر) يُكتَبُ «Passed». فَهذا السِكرِبتُ يَقرَأُ trx الخُطوَةِ الحَيَّة: النَجاحاتُ ناقِصَ ما كَتَبَ
#  العَلامَةَ `[live:returned-early]` (`LiveProofJobTests.EarlyReturnMarker`) = ما بَلَغَ القاعِدَة، ويَفشَلُ دونَ الأَرضِيَّة.
#
#  الخُروج: 0 فَوقَ الأَرضِيَّة · 1 دونَها · 2 لا trx أَو بِلا نَتيجَة أَو أَرضِيَّةٌ لَيسَت عَدَداً مُوجَباً.
#  ويَطبَعُ ما عَدَّ في الحالاتِ كُلِّها (القاعِدَة ١٠). وحارِسُه `LiveProofJobTests`.
# ═══════════════════════════════════════════════════════════════════════
set -euo pipefail

trx="${1:-}"
floor="${2:-}"
if ! [[ "$floor" =~ ^[1-9][0-9]*$ ]]; then
  echo "✗ الأَرضِيَّةُ «$floor» لَيسَت عَدَداً مُوجَباً — الاستِعمال: $0 <live.trx> <floor>" >&2
  exit 2
fi
if [ ! -s "$trx" ]; then
  echo "✗ لا trx في «$trx» — الخُطوَةُ الحَيَّةُ لَم تُسَجِّل نَتائِجَها." >&2
  exit 2
fi

# ‏`|| true` لَيسَ تَزييناً: grep بِلا تَطابُقٍ يَخرُجُ 1، وتَحتَ `pipefail` يُسقِطُ السِكرِبتَ صامِتاً قَبلَ أَن يَطبَعَ ما عَدّ.
# ‏وصُفوفُ الفاحِصِ نَفسِه (`LiveProofJobTests` — عَيِّناتٌ ونُصوصٌ لا تَمَسُّ القاعِدَة) تَجري في الخُطوَةِ ولا تُعَدُّ مِمّا بَلَغَها.
results() { { grep -o '<UnitTestResult [^>]*>' "$trx" || true; } | { grep -v 'testName="ACommerce\.Platform\.Tests\.LiveProofJobTests\.' || true; }; }
count() { { grep -o "$1" "$trx" || true; } | wc -l | tr -d ' '; }
passed=$(results | { grep -c 'outcome="Passed"' || true; })
failed=$(count '<UnitTestResult [^>]*outcome="Failed"')
# ‏(‏2026-10-25، مُراجَعَةُ تَيّارِ W8-10 الجَولَة ٢ — يُلحَقُ ولا يُعادُ حَرفٌ فَوقَه): العَلامَةُ تُعَدُّ **مَرَّةً لِكُلِّ نَتيجَةٍ ناجِحَةٍ تَحمِلُها في
# مُخرَجِها**. كانَ `count '\[live:returned-early\]'` (`grep -o … | wc -l`) يَعُدُّ كُلَّ ظُهور — فَبُرهانٌ يَكتُبُها مَرَّتَينِ يُنقِصُ «بَلَغَ القاعِدَة»
# واحِداً لَم يَرجِع، وظُهورُها في نَتيجَةٍ فاشِلَةٍ أَو في صَفِّ الفاحِصِ أَو في مُخرَجِ التَشغيلِ كُلِّه يُعَدّ. فَيُقطَعُ الـtrx عِندَ `<UnitTestResult `،
# والسِجِلُّ يَنتَهي عِندَ `</UnitTestResult>` (أَو وَسمِه إن أُغلِقَ بِـ`/>` فَلا مُخرَجَ لَه)، ويُعَدُّ إن كانَ وَسمُه `outcome="Passed"` لِغَيرِ
# `LiveProofJobTests` وفي جِسمِه العَلامَة. والسِجِلُّ بِلا وَسمِ إغلاقٍ يُعَدُّ إلى آخِرِ المِلَفّ — الخَطَأُ فيه يُنقِصُ «بَلَغَ» لا يَزيدُه.
early_results() {
  awk 'BEGIN { RS = "<UnitTestResult "; n = 0 }
       NR > 1 {
         head = substr($0, 1, index($0, ">"))
         if (head ~ /\/>$/) next
         if (head !~ /outcome="Passed"/) next
         if (head ~ /testName="ACommerce\.Platform\.Tests\.LiveProofJobTests\./) next
         end = index($0, "</UnitTestResult>")
         body = (end > 0) ? substr($0, 1, end) : $0
         if (index(body, "[live:returned-early]") > 0) n++
       }
       END { print n }' "$trx"
}
early=$(early_results)
reached=$((passed - early))
echo "البَراهينُ الحَيَّة: نَجَحَ $passed · رَجَعَ مِن حارِسٍ فَرعِيٍّ $early · بَلَغَ القاعِدَة $reached (الأَرضِيَّة $floor) · فَشِلَ $failed"

if [ "$passed" -eq 0 ] && [ "$failed" -eq 0 ]; then
  echo "✗ trx بِلا نَتيجَةٍ واحِدَة — المُرَشِّحُ لَم يَبلُغ بُرهاناً." >&2
  exit 2
fi
if [ "$reached" -lt "$floor" ]; then
  echo "✗ بَلَغَ القاعِدَةَ $reached بُرهاناً — دونَ الأَرضِيَّة $floor: بُرهانٌ سَقَطَ مِن المُرَشِّحِ أَو صارَ يَرجِعُ قَبلَ قاعِدَتِه." >&2
  exit 1
fi
